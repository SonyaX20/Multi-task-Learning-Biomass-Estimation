def warmup_lr_scheduler(optimizer, warmup_epochs, base_lr):
    def lr_lambda(epoch):
        if epoch < warmup_epochs:
            return (epoch + 1) / warmup_epochs
        return 1.0
    return optim.lr_scheduler.LambdaLR(optimizer, lr_lambda)

def compute_accuracy(pred, target):
    pred_labels = torch.argmax(pred, dim=1)  # [B]
    correct = (pred_labels == target).float()  # [B]
    total = target.size(0)
    accuracy = correct.sum().item() / total if total > 0 else 0.0
    return accuracy

def compute_map(pred, target, num_classes):
    probs = torch.softmax(pred, dim=1).cpu().numpy()  # [B, num_classes]
    target_np = target.cpu().numpy()  # [B]
    if len(target_np) == 0:
        return 0.0
    target_onehot = np.eye(num_classes)[target_np]  # [B, num_classes]
    aps = []
    for i in range(num_classes):
        if target_onehot[:, i].sum() > 0:
            try:
                ap = average_precision_score(target_onehot[:, i], probs[:, i])
                aps.append(ap)
            except:
                continue
    return np.mean(aps) if len(aps) > 0 else 0.0

class GradientScaler:
    """在反向传播后、优化器更新前缩放梯度"""

    def __init__(self, layer_scales):
        """
        layer_scales: dict, 例如 {'features.0': 0.1}
        表示 features.0 的梯度缩放到 10%
        """
        self.layer_scales = layer_scales

    def scale_gradients(self, model):
        """缩放模型梯度"""
        for name, param in model.named_parameters():
            if param.grad is not None:
                for layer_key, scale in self.layer_scales.items():
                    if layer_key in name:
                        param.grad.data.mul_(scale)
                        break

def train_classification(model, train_loader, criterion, optimizer, device, epoch=0):
    model.train()
    total_loss = 0
    total_acc = 0
    n_batches = 0

    pbar = tqdm(train_loader, desc=f"Epoch {epoch+1}")

    for batch_idx, batch_data in enumerate(pbar):
        data, target = batch_data
        data = data.to(device)
        target = target.to(device)

        optimizer.zero_grad()
        output = model(data)
        loss = criterion(output, target)
        loss.backward()
        gradient_scaler = GradientScaler({
            'features.0': 0.05,  # ← 第一层梯度缩放到 5%
            'features.1': 0.3,   # ← 第二层缩放到 30%
        })
        gradient_scaler.scale_gradients(model)
        torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
        if batch_idx == len(train_loader) - 1:
            plot_gradient_flow(model)
        optimizer.step()
        scheduler.step()
        with torch.no_grad():
            acc = compute_accuracy(output, target)

        total_loss += loss.item()
        total_acc += acc
        n_batches += 1

        pbar.set_postfix({
            'Loss': f'{loss.item():.4f}',
            'Acc': f'{acc*100:.1f}%'
        })

    avg_loss = total_loss / n_batches
    avg_acc = total_acc / n_batches

    return avg_loss, avg_acc

def evaluate_classification(model, loader, criterion, device, num_classes):
    model.eval()

    total_loss = 0
