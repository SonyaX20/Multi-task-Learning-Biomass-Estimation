class H5Dataset(Dataset):
    def __init__(self, h5_path: str, compute_stats: bool = False):
        self.h5f = h5py.File(h5_path, 'r')
        self.images = self.h5f['images']
        self.labels = self.h5f['labels']
        self.valid_indices = self._filter_nan_samples()
        self.n_samples = len(self.valid_indices)

        # 归一化参数（将在外部设置）
        self.mean = None
        self.std = None

        if compute_stats:
            self._compute_normalization_stats()

        print(f"H5Dataset: {h5_path}")
        print(f"  Valid samples: {self.n_samples:,}")

    def _filter_nan_samples(self):
        """过滤包含NaN的样本"""
        valid_indices = []
        for idx in range(len(self.h5f['labels'])):
            img = self.images[idx].astype(np.float32)
            input_bands = img[1:3]  # VV, VH
            if not np.isnan(input_bands).any():
                valid_indices.append(idx)
        return valid_indices

    def _compute_normalization_stats(self):
        """计算整个数据集的均值和标准差"""
        print("  Computing normalization statistics...")

        # 采样计算（如果数据集太大）
        sample_size = min(self.n_samples, 10000)
        sample_indices = np.random.choice(self.n_samples, sample_size, replace=False)

        all_vv = []
        all_vh = []

        for i in sample_indices:
            actual_idx = self.valid_indices[i]
            img = self.images[actual_idx].astype(np.float32)
            input_bands = img[1:3]
            all_vv.append(input_bands[0].flatten())
            all_vh.append(input_bands[1].flatten())

        all_vv = np.concatenate(all_vv)
        all_vh = np.concatenate(all_vh)

        # 计算每个通道的均值和标准差
        mean_vv, std_vv = np.mean(all_vv), np.std(all_vv)
        mean_vh, std_vh = np.mean(all_vh), np.std(all_vh)

        self.mean = torch.tensor([mean_vv, mean_vh], dtype=torch.float32).view(2, 1, 1)
        self.std = torch.tensor([std_vv, std_vh], dtype=torch.float32).view(2, 1, 1)

        # 防止除零
        self.std = torch.clamp(self.std, min=1e-6)

        print(f"  Normalization stats computed:")
        print(f"    VV - mean: {mean_vv:.4f}, std: {std_vv:.4f}")
        print(f"    VH - mean: {mean_vh:.4f}, std: {std_vh:.4f}")

    def set_normalization(self, mean, std):
        """设置归一化参数（用于验证集/测试集）"""
        self.mean = mean
        self.std = std

    def __len__(self):
        return self.n_samples

    def __getitem__(self, idx):
        actual_idx = self.valid_indices[idx]
        img = self.images[actual_idx].astype(np.float32).copy()
        input_bands = img[1:3]  # VV, VH
        label = int(self.labels[actual_idx])

        vv = torch.from_numpy(input_bands[0])  # [H, W]
        vh = torch.from_numpy(input_bands[1])  # [H, W]
        image = torch.stack([vv, vh], dim=0)   # [2, H, W]

        # 归一化
        if self.mean is not None and self.std is not None:
            image = (image - self.mean) / self.std

        label = torch.tensor(label, dtype=torch.long)
        return image, label

    def close(self):
        if hasattr(self, 'h5f'):
            self.h5f.close()

    def __del__(self):
        self.close()


class D4Augmentation:
    """D4群增强（旋转+翻转的8种组合）"""

    @staticmethod
    def apply_transform(image, transform_idx):
        """
        应用D4变换
        transform_idx: 0-7
          0: 原始
          1-3: 旋转 90°, 180°, 270°
          4: 水平翻转
          5-7: 水平翻转 + 旋转 90°, 180°, 270°
        """
        if transform_idx == 0:
            return image
        elif transform_idx <= 3:
            # 旋转 k*90度
            return torch.rot90(image, k=transform_idx, dims=[1, 2])
        else:
            # 先水平翻转，再旋转
            image = torch.flip(image, dims=[2])
            if transform_idx > 4:
                image = torch.rot90(image, k=transform_idx-4, dims=[1, 2])
            return image


