def _verify_normalization(dataloader, num_batches=5):
    """验证归一化是否正确应用"""
    print("  Verifying normalization on sample batches...")

    all_data = []
    for i, (data, _) in enumerate(dataloader):
        if i >= num_batches:
            break
        all_data.append(data)

    all_data = torch.cat(all_data, dim=0)  # [N, 2, H, W]

    # 统计
    vv_channel = all_data[:, 0, :, :]
    vh_channel = all_data[:, 1, :, :]

    print(f"  Normalized data statistics:")
    print(f"    VV channel - mean: {vv_channel.mean():.6f}, std: {vv_channel.std():.6f}, "
          f"min: {vv_channel.min():.6f}, max: {vv_channel.max():.6f}")
    print(f"    VH channel - mean: {vh_channel.mean():.6f}, std: {vh_channel.std():.6f}, "
          f"min: {vh_channel.min():.6f}, max: {vh_channel.max():.6f}")

    # 检查是否归一化
    if abs(vv_channel.mean()) < 0.1 and abs(vh_channel.mean()) < 0.1:
        if 0.8 < vv_channel.std() < 1.2 and 0.8 < vh_channel.std() < 1.2:
            print(f"  ✓ Normalization verified: data is properly normalized")
            return True

    print(f"  ⚠️  Warning: data may not be properly normalized")
    return False

