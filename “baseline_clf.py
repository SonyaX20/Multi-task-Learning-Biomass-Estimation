class PseudoHuberLoss(nn.Module):
    """
    Pseudo-Huber Loss for Classification
    PH(x) = δ² * (√(1 + (x/δ)²) - 1)

    更平滑、对异常值更鲁棒的损失函数

    Args:
        delta: 控制损失曲线形状的参数 (default: 1.0)
               - delta→0: 接近L1 loss (更鲁棒)
               - delta→∞: 接近L2 loss (更平滑)
        alpha: Per-class weights tensor [num_classes] or None
        reduction: 'mean', 'sum', or 'none'

    特性:
        - 在|x|<δ时类似L2 (平滑，易优化)
        - 在|x|>δ时类似L1 (鲁棒，对异常值不敏感)
        - 处处可微，优化友好
    """
    def __init__(self, delta=1.0, alpha=None, reduction='mean'):
        super(PseudoHuberLoss, self).__init__()
        self.delta = delta
        self.reduction = reduction

        if alpha is None:
            self.alpha = None
        elif isinstance(alpha, (float, int)):
            self.alpha = torch.tensor([alpha])
        else:
            self.alpha = alpha if isinstance(alpha, torch.Tensor) else torch.tensor(alpha)

    def forward(self, inputs, targets):
        """
        Args:
            inputs: [B, C] logits
            targets: [B] class indices
        """
        # 先计算交叉熵作为基础误差
        ce_loss = F.cross_entropy(inputs, targets, reduction='none')  # [B]

        # 应用Pseudo-Huber变换: δ² * (√(1 + (x/δ)²) - 1)
        delta_sq = self.delta ** 2
        normalized_loss = ce_loss / self.delta
        ph_loss = delta_sq * (torch.sqrt(1 + normalized_loss ** 2) - 1)

        # 应用类别权重
        if self.alpha is not None:
            if self.alpha.device != inputs.device:
                self.alpha = self.alpha.to(inputs.device)
            alpha_t = self.alpha[targets]
            ph_loss = alpha_t * ph_loss

        # 应用reduction
        if self.reduction == 'mean':
            return ph_loss.mean()
        elif self.reduction == 'sum':
            return ph_loss.sum()
        else:
            return ph_loss

def compute_class_weights(dataloader, num_classes, method='effective', beta=0.9999):
    """
    计算类别权重以处理不平衡数据

    Args:
        dataloader: 训练数据加载器
        num_classes: 类别数量
        method: 权重计算方法
            - 'inverse': 逆频率 weight = 1 / count
            - 'balanced': 平衡权重 weight = total / (n_classes * count)
            - 'effective': 有效样本数方法 weight = (1-beta) / (1-beta^count)
        beta: effective方法的超参数，默认0.9999

    Returns:
        torch.Tensor: 归一化的类别权重 [num_classes]
    """
    class_counts = torch.zeros(num_classes, dtype=torch.long)

    print(f"\n{'='*70}")
    print("统计训练集标签分布...")
    print(f"{'='*70}")

    for _, labels in tqdm(dataloader, desc="Counting labels"):
        for label in labels:
            class_counts[label.item()] += 1

    total_samples = class_counts.sum().item()

    # 计算权重
    if method == 'inverse':
        # 逆频率: w_i = 1 / count_i
        weights = 1.0 / class_counts.float()
    elif method == 'balanced':
        # 平衡权重: w_i = total / (n_classes * count_i)
        weights = total_samples / (num_classes * class_counts.float())
    elif method == 'effective':
        # 有效样本数: w_i = (1 - beta) / (1 - beta^count_i)
        effective_num = 1.0 - torch.pow(beta, class_counts.float())
        weights = (1.0 - beta) / effective_num
    else:
        raise ValueError(f"Unknown method: {method}")

    # 归一化权重，使平均权重为1
    weights = weights / weights.mean()

    # 打印标签分布和权重
    print(f"\n类别分布与权重统计:")
    print(f"{'Class':<6} {'Count':>10} {'Percentage':>12} {'Weight':>12}")
    print(f"{'-'*70}")

    for i in range(num_classes):
        count = class_counts[i].item()
        percentage = 100.0 * count / total_samples
        weight = weights[i].item()
        print(f"{i:<6} {count:>10,} {percentage:>11.2f}% {weight:>12.4f}")

    print(f"{'-'*70}")
    print(f"Total: {total_samples:>10,} {'100.00%':>12}")
    print(f"\n权重统计:")
    print(f"  Method: {method}")
    if method == 'effective':
        print(f"  Beta: {beta}")
    print(f"  Min weight: {weights.min().item():.4f}")
    print(f"  Max weight: {weights.max().item():.4f}")
    print(f"  Mean weight: {weights.mean().item():.4f}")
    print(f"  Weight ratio (max/min): {(weights.max() / weights.min()).item():.2f}x")
    print(f"{'='*70}\n")

    return weights

