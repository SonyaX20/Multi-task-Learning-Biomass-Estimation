class CNN(nn.Module):
    def __init__(self, in_channels=2, num_classes=15, base_channels=64, dropout=0.1):
        super().__init__()
        self.features = nn.Sequential(
            nn.Conv2d(in_channels, base_channels, 3, padding=1),
            nn.BatchNorm2d(base_channels),
            nn.ReLU(inplace=True),
            nn.Dropout2d(dropout),

            nn.Conv2d(base_channels, base_channels*2, 3, padding=1),
            nn.BatchNorm2d(base_channels*2),
            nn.ReLU(inplace=True),
            nn.Dropout2d(dropout),
            nn.MaxPool2d(2, 2),  # 6×6 → 3×3

            nn.Conv2d(base_channels*2, base_channels*4, 3, padding=1),
            nn.BatchNorm2d(base_channels*4),
            nn.ReLU(inplace=True),
            nn.Dropout2d(dropout),

            nn.Conv2d(base_channels*4, base_channels*8, 3, padding=0),
            nn.BatchNorm2d(base_channels*8),
            nn.ReLU(inplace=True),
            nn.AdaptiveAvgPool2d(1)
        )

        self.classifier = nn.Sequential(
            nn.Flatten(),
            nn.Dropout(dropout),
            nn.Linear(base_channels*8, num_classes)
        )

    def forward(self, x):
        x = self.features(x)      # [B, base_channels*8, 1, 1]
        x = self.classifier(x)    # [B, num_classes]
        return x

"""### Loss Functions"""

class FocalLoss(nn.Module):
    """
    Focal Loss with per-class weights
    FL(p_t) = -α_t * w_c * (1 - p_t)^γ * log(p_t)
    
    Args:
        alpha: Per-class weights tensor [num_classes] or None
        gamma: Focusing parameter (default: 2.0)
               - gamma=0: equivalent to weighted CrossEntropyLoss
               - gamma=2: recommended (from RetinaNet paper)
        reduction: 'mean', 'sum', or 'none'
    """
    def __init__(self, alpha=None, gamma=2.0, reduction='mean'):
        super(FocalLoss, self).__init__()
        self.gamma = gamma
        self.reduction = reduction
        
        if alpha is None:
            self.alpha = None
        elif isinstance(alpha, (float, int)):
            self.alpha = torch.tensor([alpha])
        else:
            self.alpha = alpha if isinstance(alpha, torch.Tensor) else torch.tensor(alpha)

    def forward(self, inputs, targets):
        """
        Args:
            inputs: [B, C] logits
            targets: [B] class indices
        """
        ce_loss = F.cross_entropy(inputs, targets, reduction='none')
        p_t = torch.exp(-ce_loss)
        focal_term = (1 - p_t) ** self.gamma
        
        if self.alpha is not None:
            if self.alpha.device != inputs.device:
                self.alpha = self.alpha.to(inputs.device)
            alpha_t = self.alpha[targets]
            focal_loss = alpha_t * focal_term * ce_loss
        else:
            focal_loss = focal_term * ce_loss
        
        if self.reduction == 'mean':
            return focal_loss.mean()
        elif self.reduction == 'sum':
            return focal_loss.sum()
        else:
            return focal_loss


class PseudoHuberLoss(nn.Module):
    """
    Pseudo-Huber Loss for Classification
    PH(x) = δ² * (√(1 + (x/δ)²) - 1)
    
    更平滑、对异常值更鲁棒的损失函数
    
    Args:
        delta: 控制损失曲线形状的参数 (default: 1.0)
               - delta→0: 接近L1 loss (更鲁棒)
               - delta→∞: 接近L2 loss (更平滑)
        alpha: Per-class weights tensor [num_classes] or None
        reduction: 'mean', 'sum', or 'none'
    
    特性:
        - 在|x|<δ时类似L2 (平滑，易优化)
        - 在|x|>δ时类似L1 (鲁棒，对异常值不敏感)
        - 处处可微，优化友好
    """
    def __init__(self, delta=1.0, alpha=None, reduction='mean'):
        super(PseudoHuberLoss, self).__init__()
        self.delta = delta
        self.reduction = reduction
        
        if alpha is None:
            self.alpha = None
        elif isinstance(alpha, (float, int)):
            self.alpha = torch.tensor([alpha])
        else:
            self.alpha = alpha if isinstance(alpha, torch.Tensor) else torch.tensor(alpha)

    def forward(self, inputs, targets):
        """
        Args:
            inputs: [B, C] logits
            targets: [B] class indices
        """
        # 先计算交叉熵作为基础误差
        ce_loss = F.cross_entropy(inputs, targets, reduction='none')  # [B]
        
        # 应用Pseudo-Huber变换: δ² * (√(1 + (x/δ)²) - 1)
        delta_sq = self.delta ** 2
        normalized_loss = ce_loss / self.delta
        ph_loss = delta_sq * (torch.sqrt(1 + normalized_loss ** 2) - 1)
        
        # 应用类别权重
        if self.alpha is not None:
            if self.alpha.device != inputs.device:
                self.alpha = self.alpha.to(inputs.device)
            alpha_t = self.alpha[targets]
            ph_loss = alpha_t * ph_loss
        
        # 应用reduction
        if self.reduction == 'mean':
            return ph_loss.mean()
        elif self.reduction == 'sum':
            return ph_loss.sum()
        else:
            return ph_loss


class CombinedLoss(nn.Module):
    """
    组合损失: Focal Loss + Pseudo-Huber Loss
    L = λ₁ * FocalLoss + λ₂ * PseudoHuberLoss
    
    结合两种损失的优势:
    - Focal Loss: 关注困难样本
    - Pseudo-Huber: 对异常值鲁棒
    
    Args:
        alpha: Per-class weights
        gamma: Focal loss focusing parameter
        delta: Pseudo-Huber delta parameter
        focal_weight: Focal loss权重 (default: 0.7)
        ph_weight: Pseudo-Huber权重 (default: 0.3)
    """
    def __init__(self, alpha=None, gamma=2.0, delta=1.0, 
                 focal_weight=0.7, ph_weight=0.3, reduction='mean'):
        super(CombinedLoss, self).__init__()
        self.focal_loss = FocalLoss(alpha=alpha, gamma=gamma, reduction=reduction)
        self.ph_loss = PseudoHuberLoss(delta=delta, alpha=alpha, reduction=reduction)
        self.focal_weight = focal_weight
        self.ph_weight = ph_weight
    
    def forward(self, inputs, targets):
        focal = self.focal_loss(inputs, targets)
        ph = self.ph_loss(inputs, targets)
        return self.focal_weight * focal + self.ph_weight * ph

