def evaluate_classification(model, loader, criterion, device, detailed=False, label_mapping=None):
    model.eval()
    total_loss = 0
    total_acc = 0
    n_batches = 0

    all_preds = []
    all_labels = []

    with torch.no_grad():
        pbar = tqdm(loader, desc="Evaluating")
        for data, target in pbar:
            data, target = data.to(device), target.to(device)
            output = model(data)

            loss = criterion(output, target)
            acc = compute_accuracy(output, target)

            total_loss += loss.item()
            total_acc += acc
            n_batches += 1

            if detailed:
                preds = torch.argmax(output, dim=1)
                all_preds.extend(preds.cpu().numpy())
                all_labels.extend(target.cpu().numpy())

            pbar.set_postfix({
                'Loss': f'{loss.item():.4f}',
                'Acc': f'{acc*100:.1f}%'
            })

    avg_loss = total_loss / n_batches
    avg_acc = total_acc / n_batches

    if not detailed:
        return avg_loss, avg_acc

    # Detailed evaluation
    all_preds = np.array(all_preds)
    all_labels = np.array(all_labels)

    # Print results
    print(f"\n{'='*70}")
    print(f"CLASSIFICATION TEST RESULTS")
    print(f"{'='*70}")
    print(f"Loss: {avg_loss:.4f}")
    print(f"Accuracy: {avg_acc*100:.2f}%")

    # Get label names
    if label_mapping and 'idx_to_label' in label_mapping:
        idx_to_label = label_mapping['idx_to_label']
        # Convert string keys to int if needed
        if isinstance(list(idx_to_label.keys())[0], str):
            idx_to_label = {int(k): v for k, v in idx_to_label.items()}
        target_names = [idx_to_label.get(i, f'Class_{i}') for i in range(len(idx_to_label))]
    else:
        target_names = None

    # Confusion Matrix
    cm = confusion_matrix(all_labels, all_preds)

    fig, ax = plt.subplots(figsize=(6, 4))
    sns.heatmap(cm, annot=True, fmt='d', cmap='Blues', ax=ax,
                xticklabels=target_names if target_names else 'auto',
                yticklabels=target_names if target_names else 'auto')
    ax.set_title('Confusion Matrix')
    ax.set_ylabel('True Label')
    ax.set_xlabel('Predicted Label')
    if target_names:
        plt.xticks(rotation=45, ha='right')
        plt.yticks(rotation=0)
    plt.tight_layout()
    plt.savefig('classification_confusion_matrix.png', dpi=300, bbox_inches='tight')
    plt.show()

    # Classification Report
    print(f"\n{'='*70}")
    print("DETAILED CLASSIFICATION REPORT")
    print(f"{'='*70}")
    print(classification_report(all_labels, all_preds,
                                target_names=target_names,
                                zero_division=0))

    # Per-class Accuracy
    class_acc = cm.diagonal() / cm.sum(axis=1)
    print(f"\n{'='*70}")
    print("PER-CLASS ACCURACY")
    print(f"{'='*70}")
    for i, acc in enumerate(class_acc):
        count = cm.sum(axis=1)[i]
        label_name = target_names[i] if target_names else f'Class {i}'
        print(f"{label_name:20s}: {acc*100:5.2f}% ({int(count):4d} samples)")

    # Summary
    print(f"\n{'='*70}")
    print("SUMMARY")
    print(f"{'='*70}")
    print(f"Overall Accuracy: {avg_acc*100:.2f}%")
    print(f"Mean Per-Class Acc: {class_acc.mean()*100:.2f}%")

    if target_names:
        print(f"Best Class: {target_names[class_acc.argmax()]} ({class_acc.max()*100:.2f}%)")
        print(f"Worst Class: {target_names[class_acc.argmin()]} ({class_acc.min()*100:.2f}%)")
    else:
        print(f"Best Class: {class_acc.argmax()} ({class_acc.max()*100:.2f}%)")
        print(f"Worst Class: {class_acc.argmin()} ({class_acc.min()*100:.2f}%)")

    # Check for never predicted classes
    unique_preds = set(all_preds)
    unique_labels = set(all_labels)
    never_predicted = unique_labels - unique_preds
    if never_predicted:
        print(f"\n⚠️ WARNING: Classes never predicted: {sorted(never_predicted)}")
        if target_names:
            never_pred_names = [target_names[i] for i in sorted(never_predicted)]
            print(f"   ({', '.join(never_pred_names)})")

    return avg_loss, avg_acc, all_preds, all_labels

