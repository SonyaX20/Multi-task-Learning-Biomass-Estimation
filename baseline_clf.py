class D4Augmentation:
    def apply_transform(image: torch.Tensor, transform_idx: int) -> torch.Tensor:
        if transform_idx == 0:
            return image
        elif transform_idx == 1:
            return torch.rot90(image, k=-1, dims=(-2, -1))
        elif transform_idx == 2:
            return torch.rot90(image, k=2, dims=(-2, -1))
        elif transform_idx == 3:
            return torch.rot90(image, k=1, dims=(-2, -1))
        elif transform_idx == 4:
            return torch.flip(image, dims=[-1])
        elif transform_idx == 5:
            return torch.flip(image, dims=[-2])
        elif transform_idx == 6:
            return torch.transpose(image, -2, -1)
        elif transform_idx == 7:
            transposed = torch.transpose(image, -2, -1)
            return torch.rot90(transposed, k=2, dims=(-2, -1))
        else:
            raise ValueError(f"Invalid transform_idx: {transform_idx}. Must be 0-7.")

class H5Dataset(Dataset):
    def __init__(self, h5_path: str):
        self.h5f = h5py.File(h5_path, 'r')
        self.images = self.h5f['images']
        self.labels = self.h5f['labels']
        self.valid_indices = self._filter_nan_samples()
        self.n_samples = len(self.valid_indices)

        print(f"H5Dataset initialized: {h5_path}")
        print(f"  Total samples: {len(self.labels)}")
        print(f"  Valid samples: {self.n_samples}")

    def _filter_nan_samples(self):
        valid_indices = []
        for idx in range(len(self.h5f['labels'])):
            img = self.images[idx].astype(np.float32)
            input_bands = img[1:3]  # VV, VH
            if not np.isnan(input_bands).any():
                valid_indices.append(idx)
        return valid_indices

    def __len__(self):
        return self.n_samples

    def __getitem__(self, idx):
        actual_idx = self.valid_indices[idx]
        img = self.images[actual_idx].astype(np.float32).copy()
        input_bands = img[1:3]  # VV, VH
        label = int(self.labels[actual_idx])

        vv = torch.from_numpy(input_bands[0])  # [H, W]
        vh = torch.from_numpy(input_bands[1])  # [H, W]
        image = torch.stack([vv, vh], dim=0)   # [2, H, W]

        label = torch.tensor(label, dtype=torch.long)
        return image, label

    def get_filename(self, idx):
        actual_idx = self.valid_indices[idx]
        return self.images.file['filenames'][actual_idx].decode('utf-8')

    def get_label_name(self, idx):
        actual_idx = self.valid_indices[idx]
        return self.images.file['label_names'][actual_idx].decode('utf-8')

    def close(self):
        if hasattr(self, 'h5f'):
            self.h5f.close()

    def __del__(self):
        self.close()

class ExplicitD4Dataset(Dataset):
    def __init__(self, base_dataset: Dataset):
        self.base_dataset = base_dataset
        self.n_transforms = 8
        self.original_size = len(base_dataset)
        self.total_size = self.original_size * self.n_transforms

        print(f"  原始样本数: {self.original_size:,}")
        print(f"  扩展后样本数: {self.total_size:,}")

    def __len__(self):
        return self.total_size

    def __getitem__(self, idx):
        original_idx = idx // self.n_transforms
        transform_idx = idx % self.n_transforms
        image, label = self.base_dataset[original_idx]
        image = D4Augmentation.apply_transform(image, transform_idx)
        return image, label

