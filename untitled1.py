class MultitaskUNet(BaseUNet):
    """UNet for multitask learning (regression + classification)

    Improved version with multi-scale features for classification.
    """

    def __init__(self, in_channels=3, out_channels=1, num_classes=10, base_channels=32, dropout=0.1,
                 use_multiscale_cls=True):
        super(MultitaskUNet, self).__init__(in_channels, base_channels, dropout)

        self.use_multiscale_cls = use_multiscale_cls

        # Residual connection for regression
        self.input_proj = nn.Conv2d(in_channels, base_channels, 1)

        # Regression decoder
        self.up1 = self._up_block(base_channels*16, base_channels*8, 1, 1, 0)
        self.up2 = self._up_block(base_channels*4, base_channels*2, 3, 1, 0)
        self.up3 = self._up_block(base_channels*2, base_channels, 2, 2, 0)

        self.dec1 = self._conv_block(base_channels*12, base_channels*4, dropout)
        self.dec2 = self._conv_block(base_channels*4, base_channels*2, dropout)
        self.dec3 = self._conv_block(base_channels*2, base_channels, dropout)

        # Regression head
        self.regression_head = nn.Sequential(
            nn.Conv2d(base_channels, base_channels//2, 3, padding=1),
            nn.BatchNorm2d(base_channels//2),
            nn.ReLU(inplace=False),
            nn.Conv2d(base_channels//2, out_channels, 1)
        )

        # Improved Classification head with multi-scale features
        if use_multiscale_cls:
            # Pool different encoder layers to same spatial size
            self.cls_pool1 = nn.AdaptiveAvgPool2d((4, 4))   # e1: 32 channels → 32*16
            self.cls_pool2 = nn.AdaptiveAvgPool2d((4, 4))   # e2: 64 channels → 64*16
            self.cls_pool3 = nn.AdaptiveAvgPool2d((4, 4))   # e3: 128 channels → 128*16
            self.cls_pool4 = nn.AdaptiveAvgPool2d((2, 2))   # b:  512 channels → 512*4

            # Total features: 32*16 + 64*16 + 128*16 + 512*4 = 5632
            # Note: e3 is base_channels*4 (128), not base_channels*8 (256)
            total_features = (base_channels * 16) + (base_channels*2 * 16) + \
                           (base_channels*4 * 16) + (base_channels*16 * 4)

            self.classification_head = nn.Sequential(
                nn.Flatten(),
                nn.Linear(total_features, base_channels*16),
                nn.BatchNorm1d(base_channels*16),
                nn.ReLU(inplace=False),
                nn.Dropout(dropout),
                nn.Linear(base_channels*16, base_channels*8),
                nn.BatchNorm1d(base_channels*8),
                nn.ReLU(inplace=False),
                nn.Dropout(dropout),
                nn.Linear(base_channels*8, num_classes)
            )
        else:
            # Original: only use bottleneck
            self.global_pool = nn.AdaptiveAvgPool2d((1, 1))
            self.classification_head = nn.Sequential(
                nn.Flatten(),
                nn.Linear(base_channels*16, base_channels*8),
                nn.BatchNorm1d(base_channels*8),
                nn.ReLU(inplace=False),
                nn.Dropout(dropout),
                nn.Linear(base_channels*8, base_channels*4),
                nn.BatchNorm1d(base_channels*4),
                nn.ReLU(inplace=False),
                nn.Dropout(dropout),
                nn.Linear(base_channels*4, num_classes)
            )

    def forward(self, x):
        input_res = self.input_proj(x)

        # Shared encoder
        e1, e2, e3, b = self.encode(x)

        # Regression branch
        d1 = self.dec1(torch.cat([self.up1(b), e3], dim=1))
        d2 = self.dec2(torch.cat([self.up2(d1), e2], dim=1))
        d3 = self.dec3(torch.cat([self.up3(d2), e1], dim=1))
        regression_output = self.regression_head(d3 + input_res)

        # Classification branch
        if self.use_multiscale_cls:
            # Use multi-scale features from all encoder layers
            f1 = self.cls_pool1(e1).flatten(1)  # (B, 32*16)
            f2 = self.cls_pool2(e2).flatten(1)  # (B, 64*16)
            f3 = self.cls_pool3(e3).flatten(1)  # (B, 256*16)
            f4 = self.cls_pool4(b).flatten(1)   # (B, 512*4)

            # Concatenate all features
            cls_features = torch.cat([f1, f2, f3, f4], dim=1)
            classification_output = self.classification_head(cls_features)
        else:
            # Original: only use bottleneck
            pooled = self.global_pool(b)
            classification_output = self.classification_head(pooled)

        return regression_output, classification_output

