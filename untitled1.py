def create_mask(pred, target):
    """Create mask for valid pixels (for regression)"""
    return ~torch.isnan(target) & ~torch.isnan(pred)

class MaskedRMSELoss(nn.Module):
    """RMSE loss that handles NaN values in target (for regression)"""

    def __init__(self):
        super(MaskedRMSELoss, self).__init__()

    def forward(self, pred, target):
        """RMSE loss computed only on valid pixels"""
        mask = create_mask(pred, target)
        if mask.sum() == 0:
            return torch.tensor(0.0, device=pred.device, requires_grad=True)
        mse = ((pred[mask] - target[mask]) ** 2).mean()
        rmse = torch.sqrt(mse + 1e-8)
        return rmse

def compute_r2(pred, target):
    """Compute R² score for regression"""
    mask = create_mask(pred, target)

    if mask.sum() == 0:
        return 0.0

    pred_valid = pred[mask]
    target_valid = target[mask]

    ss_res = ((target_valid - pred_valid) ** 2).sum()
    ss_tot = ((target_valid - target_valid.mean()) ** 2).sum()
    r2 = (1 - (ss_res / ss_tot)).item() if ss_tot > 0 else 0.0

    return r2

class RobustRegressionLoss(nn.Module):
    """
    鲁棒回归损失函数 - 专为小patch设计，处理NaN、长尾分布、异常值

    基于以下论文思想：
    1. Huber Loss - 对异常值鲁棒
    2. Balanced MSE (BMSE) - 处理长尾分布 (Yang et al. 2021)
    3. Adaptive Wing Loss - 小目标自适应权重 (Wang et al. 2019)
    4. Focal Loss for Regression - 聚焦难样本 (Lin et al. 2017 思想扩展)
    5. Gradient Preservation - 保持空间结构

    适用场景：
    - 6×6 小patch CHM回归
    - Target含NaN值（自动mask）
    - 长尾高度分布
    - 包含测量异常值
    """

    def __init__(self,
                 base_loss='huber',                # 'mse', 'mae', 'huber', 'smooth_l1'
                 use_balanced=True,                # 平衡长尾分布
                 use_adaptive_weight=True,         # 自适应权重（难样本）
                 use_gradient_loss=False,          # 梯度保持（小patch效果有限）
                 use_variance_loss=True,           # ✨ 方差保持损失（防止过度平滑）
                 use_distribution_loss=False,      # 分布匹配损失（更强的方差约束）
                 huber_delta=1.0,                  # Huber loss 阈值
                 focal_alpha=0.5,                  # Focal 权重
                 focal_gamma=2.0,                  # Focal 聚焦参数
                 gradient_weight=0.1,              # 梯度损失权重
                 variance_weight=0.3,              # ✨ 方差损失权重
                 distribution_weight=0.2):         # 分布损失权重
        super(RobustRegressionLoss, self).__init__()

        self.base_loss = base_loss
        self.use_balanced = use_balanced
        self.use_adaptive_weight = use_adaptive_weight
        self.use_gradient_loss = use_gradient_loss
        self.use_variance_loss = use_variance_loss
        self.use_distribution_loss = use_distribution_loss
        self.huber_delta = huber_delta
        self.focal_alpha = focal_alpha
        self.focal_gamma = focal_gamma
        self.gradient_weight = gradient_weight
        self.variance_weight = variance_weight
        self.distribution_weight = distribution_weight

        # 基础损失函数
        if base_loss == 'mse':
            self.criterion = nn.MSELoss(reduction='none')
        elif base_loss == 'mae':
            self.criterion = nn.L1Loss(reduction='none')
        elif base_loss == 'huber':
            self.criterion = nn.HuberLoss(reduction='none', delta=huber_delta)
        elif base_loss == 'smooth_l1':
            self.criterion = nn.SmoothL1Loss(reduction='none', beta=huber_delta)

    def forward(self, pred, target):
        """
        Args:
            pred: (B, 1, H, W) 预测CHM
            target: (B, 1, H, W) 真实CHM（可能包含NaN）
        Returns:
            loss: scalar tensor
        """
        # 1. 创建有效像素mask（处理NaN）
        mask = create_mask(pred, target)

        if mask.sum() == 0:
            return torch.tensor(0.0, device=pred.device, requires_grad=True)

        # 2. 创建安全的target副本（用0填充NaN，后面会被mask掉）
        target_safe = torch.where(mask, target, torch.zeros_like(target))

        # 3. 计算基础损失（逐像素）
        base_loss = self.criterion(pred, target_safe)  # (B, 1, H, W)

        # 4. 应用Balanced MSE（处理长尾分布）
        if self.use_balanced:
            # 根据目标值大小动态调整权重
            # 对稀有的高值区域给予更大权重
            balance_weights = self._compute_balanced_weights(target_safe, mask)
            base_loss = base_loss * balance_weights

        # 5. 应用自适应权重（聚焦难样本）
        if self.use_adaptive_weight:
            # Focal-like weighting: 难预测的像素权重更大
            adaptive_weights = self._compute_adaptive_weights(pred, target_safe, mask)
            base_loss = base_loss * adaptive_weights

        # 6. Mask并归一化
        masked_loss = (base_loss * mask).sum() / mask.sum()

        total_loss = masked_loss

        # 7. ✨ 方差保持损失（防止预测过度平滑）
        if self.use_variance_loss:
            var_loss = self._variance_preservation_loss(pred, target_safe, mask)
            total_loss = total_loss + self.variance_weight * var_loss

        # 8. 分布匹配损失（更强的统计约束）
        if self.use_distribution_loss:
            dist_loss = self._distribution_matching_loss(pred, target_safe, mask)
            total_loss = total_loss + self.distribution_weight * dist_loss

        # 9. 添加梯度保持损失（可选，对小patch可能帮助有限）
        if self.use_gradient_loss:
            grad_loss = self._gradient_preservation_loss(pred, target_safe, mask)
            total_loss = total_loss + self.gradient_weight * grad_loss

        return total_loss

    def _compute_balanced_weights(self, target, mask):
        """
        Balanced MSE: 根据目标值分布计算平衡权重

        思想来自：Yang et al. "Delving into Deep Imbalanced Regression" (ICML 2021)

        对于长尾分布的回归任务：
        - 稀有的高值/低值区域权重更大
        - 常见的中等值区域权重较小
        """
        target_valid = target[mask]

        if len(target_valid) < 10:
            # 样本太少，返回均匀权重
            return torch.ones_like(target)

        # 将目标值分桶（bins）
        n_bins = 10
        target_min = target_valid.min()
        target_max = target_valid.max()

        if target_max - target_min < 1e-6:
            return torch.ones_like(target)

        # 只对有效区域计算bin
        # 先创建一个临时的bins tensor，无效位置设为0
        bins = torch.zeros_like(target, dtype=torch.long)
        bins_valid = ((target_valid - target_min) / (target_max - target_min + 1e-8) * (n_bins - 1)).long()
        bins_valid = torch.clamp(bins_valid, 0, n_bins - 1)
        bins[mask] = bins_valid

        # 统计每个bin的样本数（只统计有效样本）
        bin_counts = torch.bincount(bins[mask].flatten(), minlength=n_bins).float()
        bin_counts = torch.clamp(bin_counts, min=1.0)  # 避免除零

        # 计算逆频率权重（稀有bin权重大）
        total_samples = mask.sum().float()
        bin_weights = total_samples / (bin_counts * n_bins)

        # 平滑权重（避免极端值）
        bin_weights = torch.clamp(bin_weights, min=0.5, max=5.0)

        # 为每个像素分配权重（无效位置保持1.0）
        weights = torch.ones_like(target, dtype=torch.float32)
        for i in range(n_bins):
            weights[bins == i] = bin_weights[i]

        return weights

    def _compute_adaptive_weights(self, pred, target, mask):
        """
        自适应权重：对难预测的像素给予更大权重

        思想来自：
        1. Focal Loss (Lin et al. 2017) - 分类任务的难样本聚焦
        2. Adaptive Wing Loss (Wang et al. 2019) - 关键点检测的自适应权重

        难度定义：预测误差大的像素更难
        """
        # 只计算有效区域的误差
        error_valid = torch.abs(pred[mask] - target[mask])

        if len(error_valid) == 0:
            return torch.ones_like(pred)

        # 归一化到 [0, 1]
        error_max = error_valid.max() + 1e-8
        error_min = error_valid.min()

        # 创建完整的error tensor（无效位置设为0）
        error = torch.zeros_like(pred)
        error[mask] = error_valid

        # 归一化误差
        normalized_error = torch.clamp(error / error_max, 0, 1)

        # Focal-style权重: (1 - pt)^gamma
        # pt可以理解为"正确性"，error大则pt小
        pt = 1.0 - normalized_error

        # 计算权重
        focal_weight = self.focal_alpha * ((1 - pt) ** self.focal_gamma)

        # ✨ 减少归一化的影响（避免过度平滑）
        # 只对有效区域计算均值
        weight_mean = focal_weight[mask].mean()

        # 温和的归一化：不除以均值，而是除以较小的值
        # 这样保持权重的动态范围，避免过度平滑
        normalization_factor = torch.clamp(weight_mean, min=0.5, max=2.0)
        focal_weight = focal_weight / (normalization_factor + 1e-8)

        # 无效区域权重设为1.0（会被mask掉，不影响结果）
        focal_weight = torch.where(mask, focal_weight, torch.ones_like(focal_weight))

        return focal_weight

    def _gradient_preservation_loss(self, pred, target, mask):
        """
        梯度保持损失：保持空间结构

        对于6×6小patch，空间梯度信息很重要
        但由于尺寸小，效果可能有限
        """
        # 水平梯度
        pred_grad_x = pred[:, :, :, 1:] - pred[:, :, :, :-1]
        target_grad_x = target[:, :, :, 1:] - target[:, :, :, :-1]
        mask_x = mask[:, :, :, 1:] & mask[:, :, :, :-1]

        # 垂直梯度
        pred_grad_y = pred[:, :, 1:, :] - pred[:, :, :-1, :]
        target_grad_y = target[:, :, 1:, :] - target[:, :, :-1, :]
        mask_y = mask[:, :, 1:, :] & mask[:, :, :-1, :]

        grad_loss = 0.0
        if mask_x.sum() > 0:
            grad_loss += ((pred_grad_x - target_grad_x) ** 2 * mask_x).sum() / mask_x.sum()
        if mask_y.sum() > 0:
            grad_loss += ((pred_grad_y - target_grad_y) ** 2 * mask_y).sum() / mask_y.sum()

        return grad_loss / 2.0

    def _variance_preservation_loss(self, pred, target, mask):
        """
        方差保持损失：防止预测过度平滑

        问题：鲁棒损失（Huber）+ 加权机制 → 预测方差 << 目标方差
        解决：显式惩罚方差差异

        思想来自：
        - "Improving Distributional Similarity for Image-to-Image Translation"
        - 保持预测的统计特性与目标一致
        """
        pred_valid = pred[mask]
        target_valid = target[mask]

        if len(pred_valid) < 10:  # 样本太少，跳过
            return torch.tensor(0.0, device=pred.device)

        # 计算方差
        pred_var = pred_valid.var()
        target_var = target_valid.var()

        # 方差比率（避免除零）
        var_ratio = pred_var / (target_var + 1e-8)

        # 惩罚方差不匹配
        # 如果 pred_var < target_var，则 var_ratio < 1，loss > 0
        # 目标是 var_ratio ≈ 1
        var_loss = (var_ratio - 1.0) ** 2

        return var_loss

    def _distribution_matching_loss(self, pred, target, mask):
        """
        分布匹配损失：匹配预测和目标的完整统计分布

        比方差损失更强：同时匹配均值、方差、偏度

        用于：严重的预测过平滑问题
        """
        pred_valid = pred[mask]
        target_valid = target[mask]

        if len(pred_valid) < 10:
            return torch.tensor(0.0, device=pred.device)

        # 1. 均值差异
        mean_loss = (pred_valid.mean() - target_valid.mean()) ** 2

        # 2. 标准差差异
        std_loss = (pred_valid.std() - target_valid.std()) ** 2

        # 3. 分位数差异（鲁棒的分布匹配）
        # 匹配 10%, 50%, 90% 分位数
        quantiles = [0.1, 0.5, 0.9]
        quantile_loss = 0.0

        for q in quantiles:
            pred_q = torch.quantile(pred_valid, q)
            target_q = torch.quantile(target_valid, q)
            quantile_loss += (pred_q - target_q) ** 2

        quantile_loss = quantile_loss / len(quantiles)

        # 组合损失（标准差权重更大，因为这是主要问题）
        dist_loss = 0.2 * mean_loss + 0.6 * std_loss + 0.2 * quantile_loss

        return dist_loss


class QuantileLoss(nn.Module):
    """
    分位数损失：对异常值极度鲁棒

    论文：Koenker & Bassett (1978) "Regression Quantiles"

    优点：
    - 不受异常值影响
    - 可以预测不确定性（多个分位数）
    - 适合长尾分布

    用法：预测多个分位数（如0.1, 0.5, 0.9），0.5为中位数预测
    """

    def __init__(self, quantiles=[0.1, 0.5, 0.9]):
        super(QuantileLoss, self).__init__()
        self.quantiles = quantiles

    def forward(self, pred, target):
        """
        Args:
            pred: (B, C, H, W) 其中 C = len(quantiles)
            target: (B, 1, H, W)
        """
        mask = create_mask(pred, target)

        if mask.sum() == 0:
            return torch.tensor(0.0, device=pred.device, requires_grad=True)

        # 创建安全的target副本
        target_safe = torch.where(mask, target, torch.zeros_like(target))

        total_loss = 0.0

        for i, q in enumerate(self.quantiles):
            if pred.shape[1] > 1:
                pred_q = pred[:, i:i+1]
            else:
                pred_q = pred

            errors = target_safe - pred_q

            # 分位数损失：max(q * e, (q-1) * e)
            loss = torch.max(q * errors, (q - 1) * errors)
            loss = (loss * mask).sum() / mask.sum()
            total_loss += loss

        return total_loss / len(self.quantiles)

