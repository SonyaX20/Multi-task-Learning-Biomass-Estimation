class ClassificationUNet(BaseUNet):
    """
    UNet for classification tasks (tree species recognition)
    Optimized for 6×6 input patches
    
    Architecture:
    ┌─────────────────────────────────────────────────────────────┐
    │                    INPUT [B, 3, 6×6]                        │
    │                  (VV, VH, VV/VH bands)                      │
    └────────────────────┬────────────────────────────────────────┘
                         │
                         ↓
    ┌────────────────────────────────────────────────────────────┐
    │              ENCODER (Shared with BaseUNet)                │
    ├────────────────────────────────────────────────────────────┤
    │  enc1:  Conv→BN→ReLU→Dropout→Conv→BN→ReLU                 │
    │         [B, 3, 6×6] → [B, 32, 6×6]                         │
    │         ↓ MaxPool(2×2)                                     │
    │  enc2:  Conv→BN→ReLU→Dropout→Conv→BN→ReLU                 │
    │         [B, 32, 3×3] → [B, 64, 3×3]                        │
    │         ↓ AdaptivePool(1×1)                                │
    │  enc3:  Conv→BN→ReLU→Dropout→Conv→BN→ReLU                 │
    │         [B, 64, 1×1] → [B, 128, 1×1]                       │
    │         ↓                                                   │
    │  bottleneck: Conv→BN→ReLU→Dropout→Conv→BN→ReLU            │
    │         [B, 128, 1×1] → [B, 256, 1×1]                      │
    └────────────────────┬───────────────────────────────────────┘
                         │
                         ↓
    ┌────────────────────────────────────────────────────────────┐
    │              CLASSIFICATION HEAD                           │
    ├────────────────────────────────────────────────────────────┤
    │  Global Pooling: [B, 256, 1×1] → [B, 256]                 │
    │         ↓                                                   │
    │  FC1:   Linear(256, 128) → BN → ReLU → Dropout            │
    │         ↓                                                   │
    │  FC2:   Linear(128, 64) → BN → ReLU → Dropout             │
    │         ↓                                                   │
    │  FC3:   Linear(64, num_classes)                            │
    └────────────────────┬───────────────────────────────────────┘
                         │
                         ↓
                  [B, num_classes]
                  (Tree species logits)
    
    Key Design Choices:
    - Uses bottleneck features (most abstract) for classification
    - No decoder needed (global pooling aggregates spatial info)
    - 3-layer FC head for sufficient non-linearity
    - Dropout for regularization
    
    Parameters (base_channels=32):
    - Encoder: ~173K (shared with regression)
    - Classification Head: ~41K
    - Total: ~214K parameters
    """

    def __init__(self, in_channels=3, num_classes=10, base_channels=32, dropout=0.1):
        super(ClassificationUNet, self).__init__(in_channels, base_channels, dropout)

        # Global pooling - reduces spatial dimensions to 1×1
        self.global_pool = nn.AdaptiveAvgPool2d((1, 1))

        # Classification head - 3 fully connected layers
        # Input: base_channels*8 = 256 (from bottleneck)
        self.classifier = nn.Sequential(
            nn.Flatten(),
            # Layer 1: 256 → 128
            nn.Linear(base_channels*8, base_channels*4),
            nn.BatchNorm1d(base_channels*4),
            nn.ReLU(inplace=False),
            nn.Dropout(dropout),
            # Layer 2: 128 → 64
            nn.Linear(base_channels*4, base_channels*2),
            nn.BatchNorm1d(base_channels*2),
            nn.ReLU(inplace=False),
            nn.Dropout(dropout),
            # Layer 3: 64 → num_classes
            nn.Linear(base_channels*2, num_classes)
        )

    def forward(self, x):
        """
        Forward pass
        
        Args:
            x: [B, 3, 6, 6] - Input SAR data (VV, VH, VV/VH)
        
        Returns:
            logits: [B, num_classes] - Class logits (not probabilities)
        """
        # Encoder - extract hierarchical features
        _, _, _, b = self.encode(x)
        # b: [B, 256, 1×1] - Bottleneck features (most abstract)

        # Global pooling - already 1×1, but ensures consistency
        pooled = self.global_pool(b)  # [B, 256, 1, 1]
        
        # Classification head
        logits = self.classifier(pooled)  # [B, num_classes]
        
        return logits

