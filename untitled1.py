def train_regression(model, train_loader, criterion, optimizer, device, epoch=0):
    model.train()
    total_loss = 0
    total_valid_ratio = 0
    n_batches = 0

    pbar = tqdm(train_loader, desc=f"Training {epoch+1}")
    for data, target in pbar:
        data, target = data.to(device), target.to(device)

        optimizer.zero_grad()
        output = model(data)
        loss = criterion(output, target)

        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
        optimizer.step()

        mask = create_mask(output, target)
        valid_ratio = mask.sum().item() / target.numel() if target.numel() > 0 else 0.0

        total_loss += loss.item()
        total_valid_ratio += valid_ratio
        n_batches += 1

        pbar.set_postfix({
            'RMSE': f'{loss.item():.4f}',
            'valid': f'{valid_ratio*100:.1f}%'
        })

    return total_loss / n_batches, total_valid_ratio / n_batches

def evaluate_regression(model, loader, criterion, device):
    """Evaluate regression model with comprehensive metrics"""
    model.eval()
    total_rmse = 0
    n_batches = 0

    # 收集所有预测值和真实值用于计算全局 R²
    all_preds = []
    all_targets = []

    with torch.no_grad():
        pbar = tqdm(loader, desc="Evaluating")
        for data, target in pbar:
            data, target = data.to(device), target.to(device)
            output = model(data)

            rmse = criterion(output, target)  # loss就是RMSE
            total_rmse += rmse.item()
            n_batches += 1

            # 收集有效的预测值和目标值
            mask = create_mask(output, target)
            if mask.sum() > 0:
                all_preds.append(output[mask].cpu())
                all_targets.append(target[mask].cpu())

            pbar.set_postfix({
                'RMSE': f'{rmse.item():.4f}'
            })

    # 在整个数据集上计算 R²
    if len(all_preds) > 0:
        all_preds = torch.cat(all_preds)
        all_targets = torch.cat(all_targets)

        ss_res = ((all_targets - all_preds) ** 2).sum()
        ss_tot = ((all_targets - all_targets.mean()) ** 2).sum()
        global_r2 = (1 - (ss_res / ss_tot)).item() if ss_tot > 0 else 0.0
    else:
        global_r2 = 0.0

    return total_rmse / n_batches, global_r2

