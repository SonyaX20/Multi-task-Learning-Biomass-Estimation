class H5Dataset(Dataset):
    def __init__(self, h5_path, task='regression', stats=None):
        """
        Dataset for regression, classification, or multitask learning

        Args:
            h5_path: Path to H5 file
            task: 'regression', 'classification', or 'multitask'
            stats: Pre-computed statistics (optional)
        """
        self.task = task
        self.h5f = h5py.File(h5_path, 'r')
        self.images = self.h5f['images']

        # Load labels for classification/multitask
        if task in ['classification', 'multitask']:
            self.labels = self.h5f['labels']
            print(f"Loaded labels with shape: {self.labels.shape}")

        self.valid_indices = self._filter_valid_samples()
        self.stats = stats if stats else self._compute_stats()

        print(f"\nDataset: {h5_path.split('/')[-1]}")
        print(f"Task: {task}")
        print(f"Samples: {len(self.valid_indices)} (filtered {self.images.shape[0] - len(self.valid_indices)} NaN)")
        if not stats:
            self._print_stats()

    def _filter_valid_samples(self):
        return [i for i in range(self.images.shape[0])
                if not np.isnan(self.images[i][1:4].astype(np.float32)).any()]

    def _normalize_inputs(self, inputs):
        normalized = np.empty_like(inputs)
        for c in range(3):
            normalized[..., c, :, :] = (2.0 * (inputs[..., c, :, :] - self.stats['input_min'][c])
                                       / self.stats['input_range'][c] - 1.0)
        return normalized

    def _compute_stats(self):
        n_sample = min(1000, len(self.valid_indices))
        indices = np.random.choice(self.valid_indices, n_sample, replace=False)

        raw_inputs = np.array([self.images[i][1:4].astype(np.float32) for i in indices])
        raw_targets = np.array([self.images[i][0:1].astype(np.float32) for i in indices])
        input_min = np.nanmin(raw_inputs, axis=(0, 2, 3))
        input_max = np.nanmax(raw_inputs, axis=(0, 2, 3))

        temp_stats = {
            'input_min': input_min,
            'input_max': input_max,
            'input_mean': np.nanmean(raw_inputs, axis=(0, 2, 3)),
            'input_std': np.nanstd(raw_inputs, axis=(0, 2, 3)),
            'input_range': input_max - input_min
        }
        self.stats = temp_stats
        norm_inputs = self._normalize_inputs(raw_inputs)
        norm_mean = np.nanmean(norm_inputs, axis=(0, 2, 3))
        norm_std = np.nanstd(norm_inputs, axis=(0, 2, 3))
        norm_min = np.nanmin(norm_inputs, axis=(0, 2, 3))
        norm_max = np.nanmax(norm_inputs, axis=(0, 2, 3))

        return {
            **temp_stats,
            'target_mean': np.nanmean(raw_targets),
            'target_std': np.nanstd(raw_targets),
            'target_min': np.nanmin(raw_targets),
            'target_max': np.nanmax(raw_targets),
            'norm_mean': norm_mean,
            'norm_std': norm_std,
            'norm_min': norm_min,
            'norm_max': norm_max
        }

    def _print_stats(self):
        s = self.stats
        channels = ['VV', 'VH', 'VV/VH']

        print("\nRaw Input Statistics:")
        for i, ch in enumerate(channels):
            print(f"  {ch}: mean={s['input_mean'][i]:.4f}, std={s['input_std'][i]:.4f}, {ch}: min={s['input_min'][i]:.2f}, max={s['input_max'][i]:.2f}")

        if self.task in ['regression', 'multitask']:
            print(f"  CHM: mean={s['target_mean']:.2f}, std={s['target_std']:.2f}, CHM: min={s['target_min']:.2f}, max={s['target_max']:.2f}")

        print("\nNormalized Statistics:")
        for i, ch in enumerate(channels):
            print(f"  {ch}: mean={s['norm_mean'][i]:.4f}, std={s['norm_std'][i]:.4f}, min={s['norm_min'][i]:.4f}, max={s['norm_max'][i]:.4f}")

        # Print label distribution for classification/multitask
        if self.task in ['classification', 'multitask']:
            print("\nLabel Distribution:")
            label_array = np.array([self.labels[i] for i in self.valid_indices])
            unique_labels, counts = np.unique(label_array, return_counts=True)
            for label, count in zip(unique_labels, counts):
                print(f"  Class {label}: {count} samples ({count/len(label_array)*100:.1f}%)")

    def __len__(self):
        return len(self.valid_indices)

    def __getitem__(self, idx):
        real_idx = self.valid_indices[idx]
        img = self.images[real_idx].astype(np.float32)
        inputs = self._normalize_inputs(img[1:4])

        if self.task == 'regression':
            # Regression: return (inputs, CHM target)
            target = img[0:1].copy()
            target[target < 1.0] = np.nan
            return torch.from_numpy(inputs), torch.from_numpy(target)

        elif self.task == 'classification':
            # Classification: return (inputs, label)
            label = torch.tensor(self.labels[real_idx], dtype=torch.long)
            return torch.from_numpy(inputs), label

        elif self.task == 'multitask':
            # Multitask: return (inputs, (CHM target, label))
            target = img[0:1].copy()
            target[target < 1.0] = np.nan
            label = torch.tensor(self.labels[real_idx], dtype=torch.long)
            return torch.from_numpy(inputs), (torch.from_numpy(target), label)

        else:
            raise ValueError(f"Unknown task: {self.task}. Must be 'regression', 'classification', or 'multitask'.")

    def get_stats(self):
        return self.stats

    def close(self):
        if hasattr(self, 'h5f'):
            self.h5f.close()

    def __del__(self):
        self.close()

def create_dataloaders(train_h5, test_h5, task='regression', batch_size=32, num_workers=2,
                       val_ratio=0.1, use_weighted_sampler=False):
    train_dataset = H5Dataset(train_h5, task=task)
    train_stats = train_dataset.get_stats()
    test_dataset = H5Dataset(test_h5, task=task, stats=train_stats)

    val_size = int(len(train_dataset) * val_ratio)
    train_size = len(train_dataset) - val_size

    torch.manual_seed(42)
    if torch.cuda.is_available():
        torch.cuda.manual_seed(42)
        torch.cuda.manual_seed_all(42)

    train_subset, val_subset = random_split(train_dataset, [train_size, val_size])
    shuffle = True
    sampler = None
    if use_weighted_sampler and task in ['classification', 'multitask']:
        print("\n" + "="*70)
        print("Creating WeightedRandomSampler for oversampling rare classes")
        print("="*70)

        # Collect labels from training subset
        train_labels = []
        for idx in train_subset.indices:
            if task == 'classification':
                _, label = train_dataset[idx]
                train_labels.append(label.item())
            elif task == 'multitask':
                _, (_, label) = train_dataset[idx]
                train_labels.append(label.item())

        train_labels = np.array(train_labels)

        class_counts = np.bincount(train_labels)
        sample_weights = 1.0 / class_counts[train_labels]

        print(f"\nClass sampling weights:")
        print(f"  Max upsampling ratio: {sample_weights.max() / sample_weights.min():.1f}x")
        print(f"  Rare classes will appear ~{class_counts.max() / class_counts.min():.1f}x more per epoch")

        sampler = WeightedRandomSampler(
            weights=torch.DoubleTensor(sample_weights),
            num_samples=len(sample_weights),
            replacement=True
        )
        shuffle = False  # Disable shuffle when using sampler

        print(f"✓ WeightedRandomSampler created")
        print("="*70)

    # create dataloaders
    train_loader = DataLoader(
        train_subset,
        batch_size=batch_size,
        shuffle=shuffle,
        sampler=sampler,
        num_workers=num_workers,
        pin_memory=True if device == 'cuda' else False
    )

    val_loader = DataLoader(
        val_subset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        pin_memory=True if device == 'cuda' else False
    )

    test_loader = DataLoader(
        test_dataset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        pin_memory=True if device == 'cuda' else False
    )

    print(f"\nDataLoaders created:")
    print(f"  Training set: {len(train_subset)} samples, {len(train_loader)} batches")
    print(f"  Validation set: {len(val_subset)} samples, {len(val_loader)} batches")
    print(f"  Test set: {len(test_dataset)} samples, {len(test_loader)} batches")

    return train_loader, val_loader, test_loader

