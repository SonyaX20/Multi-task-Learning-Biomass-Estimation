class FocalLoss(nn.Module):
    """
    Focal Loss for handling class imbalance
    Reference: Lin et al. "Focal Loss for Dense Object Detection" (ICCV 2017)

    FL(p_t) = -α_t * (1 - p_t)^γ * log(p_t)
    """

    def __init__(self, alpha=None, gamma=2.0):
        """
        Args:
            alpha: Class weights (tensor of shape [num_classes]) or None
            gamma: Focusing parameter (default: 2.0)
                   γ=0 → standard cross-entropy
                   γ=2 → strongly down-weight easy examples
            reduction: 'mean' or 'sum'
        """
        super(FocalLoss, self).__init__()
        self.alpha = alpha
        self.gamma = gamma

    def forward(self, pred, target):
        """
        Args:
            pred: (B, num_classes) - logits
            target: (B,) - class indices
        """
        # Get probabilities
        logpt = nn.functional.log_softmax(pred, dim=1)
        pt = torch.exp(logpt)

        # Get log probability of correct class
        logpt = logpt.gather(1, target.view(-1, 1)).view(-1)
        pt = pt.gather(1, target.view(-1, 1)).view(-1)

        # Apply focal term: (1 - pt)^gamma
        focal_term = (1 - pt) ** self.gamma

        # Apply class weights if provided
        if self.alpha is not None:
            if self.alpha.device != pred.device:
                self.alpha = self.alpha.to(pred.device)
            alpha_t = self.alpha.gather(0, target)
            focal_term = alpha_t * focal_term

        # Compute loss
        loss = -focal_term * logpt

        return loss.mean()

"""### Multitask"""

class MultitaskLoss(nn.Module):
    """Combined loss for multitask learning"""

    def __init__(self, reg_weight=1.0, cls_weight=1.0):
        super(MultitaskLoss, self).__init__()
        self.regression_loss = MaskedRMSELoss()
        self.classification_loss = FocalLoss(alpha=class_weights, gamma=2.0).to(device)
        self.reg_weight = reg_weight
        self.cls_weight = cls_weight

    def forward(self, reg_pred, cls_pred, reg_target, cls_target):
        reg_loss = self.regression_loss(reg_pred, reg_target)
        cls_loss = self.classification_loss(cls_pred, cls_target)
        total_loss = self.reg_weight * reg_loss + self.cls_weight * cls_loss
        return total_loss, reg_loss, cls_loss

