def plot_gradients(model, save_path='gradients.png'):
    """
    简洁的梯度可视化 - 一张图看清所有层的梯度

    用法：
        loss.backward()
        plot_gradients(model)
        optimizer.step()
    """
    grads = []
    names = []

    for name, param in model.named_parameters():
        if param.grad is not None and param.requires_grad:
            grad = param.grad.abs().mean().item()
            grads.append(grad)
            names.append(name.split('.')[-1][:15])  # 只取最后一部分，截断过长名字

    if len(grads) == 0:
        print("No gradients found!")
        return

    # 绘制
    plt.figure(figsize=(12, 4))
    plt.bar(range(len(grads)), grads, color='steelblue', alpha=0.7)
    plt.xticks(range(len(grads)), names, rotation=45, ha='right', fontsize=8)
    plt.ylabel('Mean |Gradient|')
    plt.title(f'Gradient Flow (mean={np.mean(grads):.2e}, max={np.max(grads):.2e})')
    plt.yscale('log')
    plt.grid(True, alpha=0.3, axis='y')
    plt.tight_layout()
    plt.savefig(save_path, dpi=150, bbox_inches='tight')
    plt.show()
    plt.close()
    print(f"✓ Gradient plot saved to {save_path}")


def check_gradients(model):
    """
    快速检查梯度健康状态 - 一行打印所有信息

    用法：
        loss.backward()
        check_gradients(model)
    """
    grads = [p.grad.abs() for p in model.parameters() if p.grad is not None]

    if len(grads) == 0:
        print("❌ No gradients!")
        return False

    all_grads = torch.cat([g.flatten() for g in grads])
    mean_g = all_grads.mean().item()
    max_g = all_grads.max().item()
    min_g = all_grads.min().item()

    has_nan = torch.isnan(all_grads).any().item()
    has_inf = torch.isinf(all_grads).any().item()

    status = "❌" if (has_nan or has_inf or mean_g < 1e-8) else "✓"
    print(f"{status} Gradients: mean={mean_g:.2e}, max={max_g:.2e}, min={min_g:.2e}, "
          f"NaN={has_nan}, Inf={has_inf}")

    return not (has_nan or has_inf)


def diagnose_regression_performance(model, loader, device, num_samples=100):
    """
    诊断回归性能，分析 R² 低的可能原因
    """
    model.eval()

    all_preds = []
    all_targets = []
    sample_count = 0

    print("\n" + "="*70)
    print("REGRESSION PERFORMANCE DIAGNOSTICS")
    print("="*70)

    with torch.no_grad():
        for data, target in loader:
            data, target = data.to(device), target.to(device)
            output = model(data)

            mask = create_mask(output, target)
            if mask.sum() > 0:
                all_preds.append(output[mask].cpu().numpy())
                all_targets.append(target[mask].cpu().numpy())
                sample_count += mask.sum().item()

            if sample_count >= num_samples:
                break

    if len(all_preds) == 0:
        print("No valid predictions found!")
        return

    all_preds = np.concatenate(all_preds)
    all_targets = np.concatenate(all_targets)

    # 基本统计
    print(f"\n1. Data Statistics (n={len(all_preds)} pixels):")
    print(f"   Target CHM:")
    print(f"     Mean:   {all_targets.mean():.2f} m")
    print(f"     Std:    {all_targets.std():.2f} m")
    print(f"     Range:  [{all_targets.min():.2f}, {all_targets.max():.2f}] m")
    print(f"   Predicted CHM:")
    print(f"     Mean:   {all_preds.mean():.2f} m")
    print(f"     Std:    {all_preds.std():.2f} m")
    print(f"     Range:  [{all_preds.min():.2f}, {all_preds.max():.2f}] m")

    # 误差分析
    errors = all_targets - all_preds
    print(f"\n2. Error Analysis:")
    print(f"   MAE:  {np.abs(errors).mean():.2f} m")
    print(f"   RMSE: {np.sqrt((errors**2).mean()):.2f} m")
    print(f"   Error range: [{errors.min():.2f}, {errors.max():.2f}] m")

    # R² 分析
    ss_res = ((all_targets - all_preds) ** 2).sum()
    ss_tot = ((all_targets - all_targets.mean()) ** 2).sum()
    r2 = 1 - (ss_res / ss_tot) if ss_tot > 0 else 0.0

    print(f"\n3. R² Analysis:")
    print(f"   R² = {r2:.4f}")
    print(f"   SS_res (残差平方和):  {ss_res:.2f}")
    print(f"   SS_tot (总平方和):    {ss_tot:.2f}")
    print(f"   Ratio (SS_res/SS_tot): {ss_res/ss_tot:.4f}")

    # 可能的问题诊断
    print(f"\n4. Possible Issues:")
    if all_preds.std() < all_targets.std() * 0.3:
        print(f"   ⚠️  Predictions are too smooth (std_pred << std_target)")
        print(f"      Model may be under-predicting variance")

    if abs(all_preds.mean() - all_targets.mean()) > all_targets.std() * 0.5:
        print(f"   ⚠️  Large bias: mean prediction differs from mean target")
        print(f"      Bias: {all_preds.mean() - all_targets.mean():.2f} m")

    if r2 < 0:
        print(f"   ⚠️  Negative R²: Model performs worse than mean prediction!")
        print(f"      The model is not learning effectively")
    elif r2 < 0.3:
        print(f"   ⚠️  Very low R²: Model explains < 30% of variance")
        print(f"      Consider: 1) More training, 2) Better architecture, 3) Data quality")

    # 相关性检查
    correlation = np.corrcoef(all_targets, all_preds)[0, 1]
    print(f"\n5. Correlation Analysis:")
