def train_multitask(model, train_loader, criterion, optimizer, device, epoch=0):
    """Train multitask model"""
    model.train()
    total_loss = 0
    total_reg_loss = 0
    total_cls_loss = 0
    total_r2 = 0
    total_acc = 0
    n_batches = 0

    pbar = tqdm(train_loader, desc=f"Training {epoch+1}")
    for data, (reg_target, cls_target) in pbar:
        data = data.to(device)
        reg_target = reg_target.to(device)
        cls_target = cls_target.to(device)

        optimizer.zero_grad()
        reg_output, cls_output = model(data)
        loss, reg_loss, cls_loss = criterion(reg_output, cls_output, reg_target, cls_target)

        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
        optimizer.step()

        r2 = compute_r2(reg_output, reg_target)
        acc = compute_accuracy(cls_output, cls_target)

        total_loss += loss.item()
        total_reg_loss += reg_loss.item()
        total_cls_loss += cls_loss.item()
        total_r2 += r2
        total_acc += acc
        n_batches += 1

        pbar.set_postfix({
            'Loss': f'{loss.item():.4f}',
            'R²': f'{r2:.3f}',
            'Acc': f'{acc*100:.1f}%'
        })

    return (total_loss / n_batches, total_reg_loss / n_batches,
            total_cls_loss / n_batches, total_r2 / n_batches, total_acc / n_batches)

