class RegressionUNet(BaseUNet):
    """
    UNet for regression tasks (e.g., CHM prediction)
    Optimized for 6×6 input patches

    Decoder path:
    bottleneck [256, 1, 1] → up1 → d1 [64, 1, 1]
                                    ↓
    e3 [128, 1, 1] ─────────────────┘

    d1 [64, 1, 1] → up2 → d2 [32, 3, 3]
                          ↓
    e2 [64, 3, 3] ────────┘

    d2 [32, 3, 3] → up3 → d3 [32, 6, 6]
                          ↓
    e1 [32, 6, 6] ────────┘

    d3 [32, 6, 6] + residual → final → [1, 6, 6]
    """

    def __init__(self, in_channels=3, out_channels=1, base_channels=32, dropout=0.1):
        super(RegressionUNet, self).__init__(in_channels, base_channels, dropout)

        # Residual connection from input
        self.input_proj = nn.Conv2d(in_channels, base_channels, 1)

        # ============ Decoder (3 stages, matching 3-layer encoder) ============

        # Stage 1: 1×1 → 1×1 (channel reduction)
        self.up1 = self._up_block(base_channels*8, base_channels*4, 1, 1, 0)  # 256→128
        # After concat with e3 (128): 256 channels total
        self.dec1 = self._conv_block(base_channels*8, base_channels*2, dropout)  # 256→64

        # Stage 2: 1×1 → 3×3 (upsample)
        self.up2 = self._up_block(base_channels*2, base_channels*2, 3, 3, 0)  # 64→64, 1×1→3×3
        # After concat with e2 (64): 128 channels total
        self.dec2 = self._conv_block(base_channels*4, base_channels, dropout)  # 128→32

        # Stage 3: 3×3 → 6×6 (upsample)
        self.up3 = self._up_block(base_channels, base_channels, 2, 2, 0)  # 32→32, 3×3→6×6
        # After concat with e1 (32): 64 channels total
        self.dec3 = self._conv_block(base_channels*2, base_channels, dropout)  # 64→32

        # Regression head
        self.final = nn.Sequential(
            nn.Conv2d(base_channels, base_channels//2, 3, padding=1),
            nn.BatchNorm2d(base_channels//2),
            nn.ReLU(inplace=False),
            nn.Conv2d(base_channels//2, out_channels, 1)
        )

    def forward(self, x):
        """
        Forward pass

        Args:
            x: [B, 3, 6, 6] - Input SAR data (VV, VH, VV/VH)

        Returns:
            output: [B, 1, 6, 6] - Predicted CHM (non-negative due to Softplus)
        """
        input_res = self.input_proj(x)  # [B, 32, 6, 6]

        # Encoder
        e1, e2, e3, b = self.encode(x)
        # e1: [B, 32, 6, 6]
        # e2: [B, 64, 3, 3]
        # e3: [B, 128, 1, 1]
        # b:  [B, 256, 1, 1]

        # Decoder with skip connections
        d1 = self.dec1(torch.cat([self.up1(b), e3], dim=1))    # [B, 64, 1, 1]
        d2 = self.dec2(torch.cat([self.up2(d1), e2], dim=1))   # [B, 32, 3, 3]
        d3 = self.dec3(torch.cat([self.up3(d2), e1], dim=1))   # [B, 32, 6, 6]

        # Final output with residual connection
        output = self.final(d3 + input_res)  # [B, 1, 6, 6]

        # ✨ Ensure non-negative output (CHM cannot be negative)
        # output = nn.functional.softplus(output, beta=1)

        return output

