class BaseUNet(nn.Module):
    """
    Base UNet optimized for 6×6 small patches

    Architecture (3-layer encoder):
    Input:  [B, 3, 6, 6]
    enc1:   [B, 32, 6, 6]   # No pooling
    enc2:   [B, 64, 3, 3]   # After MaxPool(2,2)
    enc3:   [B, 128, 1, 1]  # After AdaptivePool(1,1)
    bottleneck: [B, 256, 1, 1]

    For 6×6 input, this prevents over-downsampling and maintains
    meaningful spatial information at each level.
    """

    def __init__(self, in_channels=3, base_channels=32, dropout=0.1):
        super(BaseUNet, self).__init__()
        self.base_channels = base_channels

        # ============ Encoder (3 layers) ============
        # Optimized for 6×6 input - removed redundant enc4
        self.enc1 = self._conv_block(in_channels, base_channels, dropout)        # 6×6
        self.enc2 = self._conv_block(base_channels, base_channels*2, dropout)    # 3×3
        self.enc3 = self._conv_block(base_channels*2, base_channels*4, dropout)  # 1×1
        self.bottleneck = self._conv_block(base_channels*4, base_channels*8, dropout)  # 1×1

        # Pooling layers
        self.pool1 = nn.MaxPool2d(2, 2)              # 6×6 → 3×3
        self.pool2 = nn.AdaptiveMaxPool2d((1, 1))    # 3×3 → 1×1

    def _conv_block(self, in_ch, out_ch, dropout):
        """Convolutional block with BatchNorm and ReLU"""
        return nn.Sequential(
            nn.Conv2d(in_ch, out_ch, 3, padding=1),
            nn.BatchNorm2d(out_ch),
            nn.ReLU(inplace=False),
            nn.Dropout2d(dropout) if dropout > 0 else nn.Identity(),
            nn.Conv2d(out_ch, out_ch, 3, padding=1),
            nn.BatchNorm2d(out_ch),
            nn.ReLU(inplace=False)
        )

    def _up_block(self, in_ch, out_ch, kernel, stride, padding):
        """Upsampling block for decoder"""
        if kernel == 1:
            return nn.Sequential(
                nn.Conv2d(in_ch, out_ch, 1),
                nn.BatchNorm2d(out_ch),
                nn.ReLU(inplace=False)
            )
        return nn.Sequential(
            nn.ConvTranspose2d(in_ch, out_ch, kernel, stride, padding),
            nn.BatchNorm2d(out_ch),
            nn.ReLU(inplace=False)
        )

    def encode(self, x):
        """
        Forward pass through encoder, returns features at different scales

        Returns:
            e1: [B, 32, 6, 6]   - Low-level features (textures)
            e2: [B, 64, 3, 3]   - Mid-level features (patterns)
            e3: [B, 128, 1, 1]  - High-level features (semantics)
            b:  [B, 256, 1, 1]  - Bottleneck (most abstract)
        """
        e1 = self.enc1(x)                   # [B, 32, 6, 6]
        e2 = self.enc2(self.pool1(e1))      # [B, 64, 3, 3]
        e3 = self.enc3(self.pool2(e2))      # [B, 128, 1, 1]
        b = self.bottleneck(e3)             # [B, 256, 1, 1]
        return e1, e2, e3, b

