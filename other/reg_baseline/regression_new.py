class H5Dataset(Dataset):
    def __init__(self, h5_path, stats=None):
        self.h5f = h5py.File(h5_path, 'r')
        self.images = self.h5f['images']

        self.valid_indices = self._filter_valid_samples()
        self.stats = stats if stats else self._compute_stats()

        print(f"\nDataset: {h5_path.split('/')[-1]}")
        print(f"Samples: {len(self.valid_indices)} (filtered {self.images.shape[0] - len(self.valid_indices)} NaN)")
        if not stats:
            self._print_stats()

    def _filter_valid_samples(self):
        return [i for i in range(self.images.shape[0])
                if not np.isnan(self.images[i][1:4].astype(np.float32)).any()]

    def _normalize_inputs(self, inputs):
        normalized = np.empty_like(inputs)
        for c in range(3):
            normalized[..., c, :, :] = (2.0 * (inputs[..., c, :, :] - self.stats['input_min'][c])
                                       / self.stats['input_range'][c] - 1.0)
        return normalized

    def _compute_stats(self):
        n_sample = min(1000, len(self.valid_indices))
        indices = np.random.choice(self.valid_indices, n_sample, replace=False)

        raw_inputs = np.array([self.images[i][1:4].astype(np.float32) for i in indices])
        raw_targets = np.array([self.images[i][0:1].astype(np.float32) for i in indices])
        input_min = np.nanmin(raw_inputs, axis=(0, 2, 3))
        input_max = np.nanmax(raw_inputs, axis=(0, 2, 3))

        temp_stats = {
            'input_min': input_min,
            'input_max': input_max,
            'input_mean': np.nanmean(raw_inputs, axis=(0, 2, 3)),
            'input_std': np.nanstd(raw_inputs, axis=(0, 2, 3)),
            'input_range': input_max - input_min
        }
        self.stats = temp_stats
        norm_inputs = self._normalize_inputs(raw_inputs)
        norm_mean = np.nanmean(norm_inputs, axis=(0, 2, 3))
        norm_std = np.nanstd(norm_inputs, axis=(0, 2, 3))
        norm_min = np.nanmin(norm_inputs, axis=(0, 2, 3))
        norm_max = np.nanmax(norm_inputs, axis=(0, 2, 3))

        return {
            **temp_stats,
            'target_mean': np.nanmean(raw_targets),
            'target_std': np.nanstd(raw_targets),
            'target_min':np.nanmax(raw_targets),
            'target_max':np.nanmax(raw_targets),
            'norm_mean': norm_mean,
            'norm_std': norm_std,
            'norm_min': norm_min,
            'norm_max': norm_max
        }

    def _print_stats(self):
        s = self.stats
        channels = ['VV', 'VH', 'VV/VH']

        print("\nRaw Input Statistics:")
        for i, ch in enumerate(channels):
            print(f"  {ch}: mean={s['input_mean'][i]:.4f}, std={s['input_std'][i]:.4f}, {ch}: min={s['input_min'][i]:.2f}, max={s['input_max'][i]:.2f}")
        print(f"  CHM: mean={s['target_mean']:.2f}, std={s['target_std']:.2f}, CHM: min={s['target_min']:.2f}, max={s['target_max']:.2f}")

        print("\nNormalized Statistics:")
        for i, ch in enumerate(channels):
            print(f"  {ch}: mean={s['norm_mean'][i]:.4f}, std={s['norm_std'][i]:.4f}, min={s['norm_min'][i]:.4f}, max={s['norm_max'][i]:.4f}")

    def __len__(self):
        return len(self.valid_indices)

    def __getitem__(self, idx):
        img = self.images[self.valid_indices[idx]].astype(np.float32)
        inputs = self._normalize_inputs(img[1:4])

        target = img[0:1].copy()
        target[target < 1.0] = np.nan

        return torch.from_numpy(inputs), torch.from_numpy(target)

    def get_stats(self):
        return self.stats

    def close(self):
        if hasattr(self, 'h5f'):
            self.h5f.close()

    def __del__(self):
        self.close()

def create_dataloaders(train_h5, test_h5, batch_size=32, num_workers=2, val_ratio=0.1):
    train_dataset = H5Dataset(train_h5)
    train_stats = train_dataset.get_stats()
    test_dataset = H5Dataset(test_h5)

    val_size = int(len(train_dataset) * val_ratio)
    train_size = len(train_dataset) - val_size

    torch.manual_seed(42)
    if torch.cuda.is_available():
        torch.cuda.manual_seed(42)
        torch.cuda.manual_seed_all(42)

    train_subset, val_subset = random_split(train_dataset, [train_size, val_size])

    # create dataloaders
    train_loader = DataLoader(
        train_subset,
        batch_size=batch_size,
        shuffle=True,
        num_workers=num_workers,
        pin_memory=True if device == 'cuda' else False
    )

    val_loader = DataLoader(
        val_subset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        pin_memory=True if device == 'cuda' else False
    )

    test_loader = DataLoader(
        test_dataset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        pin_memory=True if device == 'cuda' else False
    )

    print(f"\nDataLoaders created:")
    print(f"  Training set: {len(train_subset)} samples, {len(train_loader)} batches")
    print(f"  Validation set: {len(val_subset)} samples, {len(val_loader)} batches")
    print(f"  Test set: {len(test_dataset)} samples, {len(test_loader)} batches")

    return train_loader, val_loader, test_loader

"""### Model Definition"""

class RegressionUNet(nn.Module):
    def __init__(self, in_channels=3, out_channels=1, base_channels=32, dropout=0.1):
        super(RegressionUNet, self).__init__()

        self.input_proj = nn.Conv2d(in_channels, base_channels, 1)

        self.enc1 = self._conv_block(in_channels, base_channels, dropout)
        self.enc2 = self._conv_block(base_channels, base_channels*2, dropout)
        self.enc3 = self._conv_block(base_channels*2, base_channels*4, dropout)
        self.enc4 = self._conv_block(base_channels*4, base_channels*8, dropout)
        self.bottleneck = self._conv_block(base_channels*8, base_channels*16, dropout)

        self.pool1 = nn.MaxPool2d(2, 2)
        self.pool2 = nn.AdaptiveMaxPool2d((1, 1))

        self.up1 = self._up_block(base_channels*16, base_channels*8, 1, 1, 0)
        self.up2 = self._up_block(base_channels*4, base_channels*2, 3, 1, 0)
        self.up3 = self._up_block(base_channels*2, base_channels, 2, 2, 0)

        self.dec1 = self._conv_block(base_channels*12, base_channels*4, dropout)
        self.dec2 = self._conv_block(base_channels*4, base_channels*2, dropout)
        self.dec3 = self._conv_block(base_channels*2, base_channels, dropout)

        self.final = nn.Sequential(
            nn.Conv2d(base_channels, base_channels//2, 3, padding=1),
            nn.BatchNorm2d(base_channels//2),
            nn.ReLU(inplace=False),
            nn.Conv2d(base_channels//2, out_channels, 1)
        )

    def _conv_block(self, in_ch, out_ch, dropout):
        return nn.Sequential(
            nn.Conv2d(in_ch, out_ch, 3, padding=1),
            nn.BatchNorm2d(out_ch),
            nn.ReLU(inplace=False),
            nn.Dropout2d(dropout) if dropout > 0 else nn.Identity(),
            nn.Conv2d(out_ch, out_ch, 3, padding=1),
            nn.BatchNorm2d(out_ch),
            nn.ReLU(inplace=False)
        )

    def _up_block(self, in_ch, out_ch, kernel, stride, padding):
        if kernel == 1:
            return nn.Sequential(
                nn.Conv2d(in_ch, out_ch, 1),
                nn.BatchNorm2d(out_ch),
                nn.ReLU(inplace=False)
            )
        return nn.Sequential(
            nn.ConvTranspose2d(in_ch, out_ch, kernel, stride, padding),
            nn.BatchNorm2d(out_ch),
            nn.ReLU(inplace=False)
        )

    def forward(self, x):
        input_res = self.input_proj(x)

        e1 = self.enc1(x)
        e2 = self.enc2(self.pool1(e1))
        e3 = self.enc3(self.pool2(e2))
        e4 = self.enc4(e3)
        b = self.bottleneck(e4)

        d1 = self.dec1(torch.cat([self.up1(b), e3], dim=1))
        d2 = self.dec2(torch.cat([self.up2(d1), e2], dim=1))
        d3 = self.dec3(torch.cat([self.up3(d2), e1], dim=1))

        return self.final(d3 + input_res)

"""### Loss Function"""

def create_mask(pred, target):
    """create mask for valid pixels"""
    return ~torch.isnan(target) & ~torch.isnan(pred)

class MaskedRMSELoss(nn.Module):
    def __init__(self):
        super(MaskedRMSELoss, self).__init__()

    def forward(self, pred, target):
        """RMSE loss scalar, computed only on valid pixels)"""
        mask = create_mask(pred, target)
        if mask.sum() == 0:
            return torch.tensor(0.0, device=pred.device, requires_grad=True)
        mse = ((pred[mask] - target[mask]) ** 2).mean()
        rmse = torch.sqrt(mse + 1e-8)

        return rmse

def compute_r2(pred, target):
    mask = create_mask(pred, target)

    if mask.sum() == 0:
        return 0.0

    pred_valid = pred[mask]
    target_valid = target[mask]

    ss_res = ((target_valid - pred_valid) ** 2).sum()
    ss_tot = ((target_valid - target_valid.mean()) ** 2).sum()
    r2 = (1 - (ss_res / ss_tot)).item() if ss_tot > 0 else 0.0

    return r2

