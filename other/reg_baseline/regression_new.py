def train_regression(model, train_loader, criterion, optimizer, device, epoch=0):
    model.train()
    total_loss = 0
    n_batches = 0

    pbar = tqdm(train_loader, desc=f"Training {epoch+1}")
    for data, target in pbar:
        data, target = data.to(device), target.to(device)

        optimizer.zero_grad()
        output = model(data)
        loss = criterion(output, target)

        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
        optimizer.step()

        mask = create_mask(output, target)

        total_loss += loss.item()
        n_batches += 1

        pbar.set_postfix({
            'RMSE': f'{loss.item():.4f}',
        })

    return total_loss / n_batches

def evaluate_regression(model, loader, criterion, device):
    """Evaluate regression model with comprehensive metrics"""
    model.eval()
    total_rmse = 0
    total_r2 = 0
    n_batches = 0

    with torch.no_grad():
        pbar = tqdm(loader, desc="Evaluating")
        for data, target in pbar:
            data, target = data.to(device), target.to(device)
            output = model(data)

            rmse = criterion(output, target)  # loss就是RMSE
            r2 = compute_r2(output, target)

            total_rmse += rmse.item()
            total_r2 += r2
            n_batches += 1

            pbar.set_postfix({
                'RMSE': f'{rmse.item():.4f}',
                'r^2': f'{r2:.3f}'
            })

    return total_rmse / n_batches, total_r2 / n_batches

