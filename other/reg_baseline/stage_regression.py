def collect_layer_gradients(model):
    """Collect mean absolute gradient for each layer"""
    layer_grads = {}
    for name, param in model.named_parameters():
        if param.grad is not None:
            grad_mean_abs = param.grad.abs().mean().item()
            layer_grads[name] = grad_mean_abs
    return layer_grads

def train_regression_swin(model, train_loader, criterion, optimizer, scheduler, device, epoch,
                         use_mixup=True, mixup_alpha=1.0, return_grads=False):
    """
    训练函数（支持MixUp数据增强）
    Args:
        model: 模型
        train_loader: 训练数据加载器
        criterion: 损失函数
        optimizer: 优化器
        scheduler: 学习率调度器
        device: 设备
        epoch: 当前epoch
        use_mixup: 是否使用MixUp
        mixup_alpha: MixUp参数
        return_grads: 是否返回梯度信息
    """
    model.train()
    total_loss = 0
    n_batches = 0
    layer_grads = None

    pbar = tqdm(train_loader, desc=f"Epoch {epoch+1}")

    for step, (data, target) in enumerate(pbar):
        data, target = data.to(device), target.to(device)

        # MixUp数据增强
        if use_mixup and model.training:
            mixed_data, target_a, target_b, lam = mixup_data(data, target, alpha=mixup_alpha)
            optimizer.zero_grad()
            output = model(mixed_data)
            loss = mixup_criterion(criterion, output, target_a, target_b, lam)
        else:
            optimizer.zero_grad()
            output = model(data)
            loss = criterion(output, target)

        loss.backward()

        # Gradient clipping for stability
        torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)

        # Collect gradients if needed
        if return_grads and step == len(train_loader) - 1:
            layer_grads = collect_layer_gradients(model)

        optimizer.step()
        scheduler.step()  # OneCycleLR需要每个batch更新

        total_loss += loss.item()
        n_batches += 1

        pbar.set_postfix({
            'Loss': f'{loss.item():.4f}',
            'LR': f'{scheduler.get_last_lr()[0]:.2e}'
        })

    avg_loss = total_loss / n_batches

    return avg_loss, layer_grads

def train_regression_paper(model, train_dataset, criterion, optimizer, scheduler, device, epoch,
                           steps_per_epoch=100, batch_size=128, return_grads=False):
    """
    Training function according to paper specifications:
    - Random batch selection
    - Fixed steps per epoch (default: 100 steps)
    Adapted from baseline_clf.py train_classification_paper
    """
    model.train()
    total_loss = 0
    total_valid_ratio = 0
    n_batches = 0

    # Create indices for random batch selection
    total_samples = len(train_dataset)

    pbar = tqdm(range(steps_per_epoch), desc=f"Epoch {epoch+1}")

    for step in pbar:
        # Randomly select batch indices
        indices = torch.randint(0, total_samples, (batch_size,))

        # Get batch data
        batch_data = []
        batch_targets = []
        for idx in indices:
            data, target = train_dataset[idx.item()]
            batch_data.append(data)
            batch_targets.append(target)

        data = torch.stack(batch_data).to(device)
        target = torch.stack(batch_targets).to(device)

        optimizer.zero_grad()
        output = model(data)
        loss = criterion(output, target)
        loss.backward()

        # Gradient clipping for stability
        torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)

        # Collect gradients if needed
        if return_grads and step == steps_per_epoch - 1:
            layer_grads = collect_layer_gradients(model)

        optimizer.step()

        with torch.no_grad():
            mask = create_mask(output, target)
            valid_ratio = mask.sum().item() / target.numel() if target.numel() > 0 else 0.0

        total_loss += loss.item()
        total_valid_ratio += valid_ratio
        n_batches += 1

        pbar.set_postfix({
            'Loss': f'{loss.item():.4f}',
            'Valid': f'{valid_ratio*100:.1f}%'
        })

    avg_loss = total_loss / n_batches
    avg_valid_ratio = total_valid_ratio / n_batches

    if return_grads:
        return avg_loss, avg_valid_ratio, layer_grads
    return avg_loss, avg_valid_ratio

def evaluate_regression(model, loader, criterion, device):
    """Evaluate regression model with comprehensive metrics"""
    model.eval()
    total_loss = 0
    total_rmse = 0
    total_r2 = 0
    n_batches = 0

    with torch.no_grad():
        pbar = tqdm(loader, desc="Evaluating")
        for data, target in pbar:
            data, target = data.to(device), target.to(device)
            output = model(data)

            # 计算损失（MSE）
            loss = criterion(output, target)
            
            # 计算RMSE（用于显示）
            mask = create_mask(output, target)
            if mask.sum() > 0:
                mse = ((output[mask] - target[mask]) ** 2).mean()
                rmse = torch.sqrt(mse + 1e-8)
            else:
                rmse = torch.tensor(0.0)
            
            r2 = compute_r2(output, target)

            total_loss += loss.item()
            total_rmse += rmse.item()
            total_r2 += r2
            n_batches += 1

            pbar.set_postfix({
                'Loss': f'{loss.item():.4f}',
                'RMSE': f'{rmse.item():.4f}',
                'R²': f'{r2:.3f}'
            })

    return total_loss / n_batches, total_r2 / n_batches

