class InputPreprocessing(nn.Module):
    """
    输入预处理层：
    1. Depthwise Convolution: 2通道 → 48通道
    2. Pointwise Convolution: 48通道 → 3通道
    """
    def __init__(self, in_channels=2, mid_channels=48, out_channels=3):
        super().__init__()
        # Depthwise Convolution: 每个输入通道独立卷积
        self.depthwise = nn.Conv2d(
            in_channels, mid_channels, 
            kernel_size=3, padding=1, 
            groups=in_channels, bias=False
        )
        self.dw_bn = nn.BatchNorm2d(mid_channels)
        self.dw_act = nn.GELU()
        
        # Pointwise Convolution: 1x1卷积整合通道
        self.pointwise = nn.Conv2d(mid_channels, out_channels, kernel_size=1, bias=False)
        self.pw_bn = nn.BatchNorm2d(out_channels)
        self.pw_act = nn.GELU()
    
    def forward(self, x):
        # x: [B, 2, 6, 6]
        x = self.depthwise(x)  # [B, 48, 6, 6]
        x = self.dw_bn(x)
        x = self.dw_act(x)
        
        x = self.pointwise(x)  # [B, 3, 6, 6]
        x = self.pw_bn(x)
        x = self.pw_act(x)
        
        return x

class ChannelAttention(nn.Module):
    """通道注意力模块"""
    def __init__(self, channels, reduction=16):
        super().__init__()
        self.avg_pool = nn.AdaptiveAvgPool2d(1)
        self.max_pool = nn.AdaptiveMaxPool2d(1)
        
        self.fc = nn.Sequential(
            nn.Linear(channels, channels // reduction, bias=False),
            nn.ReLU(),
            nn.Linear(channels // reduction, channels, bias=False)
        )
        self.sigmoid = nn.Sigmoid()

    def forward(self, x):
        # x: [B, C, H, W]
        b, c, _, _ = x.size()
        
        # 平均池化和最大池化
        avg_out = self.fc(self.avg_pool(x).view(b, c))
        max_out = self.fc(self.max_pool(x).view(b, c))
        
        # 相加并通过sigmoid
        out = avg_out + max_out
        out = self.sigmoid(out).view(b, c, 1, 1)
        
        return x * out

class SpatialAttention(nn.Module):
    """空间注意力模块"""
    def __init__(self, kernel_size=7):
        super().__init__()
        self.conv = nn.Conv2d(
            2, 1, kernel_size=kernel_size, 
            padding=kernel_size // 2, bias=False
        )
        self.sigmoid = nn.Sigmoid()
    
    def forward(self, x):
        # x: [B, C, H, W]
        # 在通道维度上做平均池化和最大池化
        avg_out = torch.mean(x, dim=1, keepdim=True)
        max_out, _ = torch.max(x, dim=1, keepdim=True)
        
        # 拼接并卷积
        out = torch.cat([avg_out, max_out], dim=1)
        out = self.conv(out)
        out = self.sigmoid(out)
        
        return x * out

class CBAMC(nn.Module):
    """
    CBAMC注意力模块：Channel Attention + Spatial Attention
    公式：X5 = M_c × X4 × M_s
    """
    def __init__(self, channels, reduction=16, kernel_size=7):
        super().__init__()
        self.channel_attention = ChannelAttention(channels, reduction)
        self.spatial_attention = SpatialAttention(kernel_size)
    
    def forward(self, x):
        # 先应用通道注意力
        x = self.channel_attention(x)
        # 再应用空间注意力
        x = self.spatial_attention(x)
        return x

class PatchEmbedding(nn.Module):
    """Patch Embedding for 6x6 input"""
    def __init__(self, img_size=6, patch_size=2, in_chans=3, embed_dim=96):
        super().__init__()
        self.img_size = img_size
        self.patch_size = patch_size
        self.n_patches = (img_size // patch_size) ** 2
        self.embed_dim = embed_dim
        
        self.proj = nn.Conv2d(in_chans, embed_dim, kernel_size=patch_size, stride=patch_size)
        self.norm = nn.LayerNorm(embed_dim)
    
    def forward(self, x):
        # x: [B, C, H, W]
        x = self.proj(x)  # [B, embed_dim, H/patch_size, W/patch_size]
        B, C, H, W = x.shape
        x = x.flatten(2).transpose(1, 2)  # [B, N, embed_dim]
        x = self.norm(x)
        return x, (H, W)

class WindowAttention(nn.Module):
    """Window-based Multi-head Self Attention"""
    def __init__(self, dim, window_size, num_heads, qkv_bias=True, attn_drop=0., proj_drop=0.):
        super().__init__()
        self.dim = dim
        self.window_size = window_size
        self.num_heads = num_heads
        head_dim = dim // num_heads
        self.scale = head_dim ** -0.5
        
        self.qkv = nn.Linear(dim, dim * 3, bias=qkv_bias)
        self.attn_drop = nn.Dropout(attn_drop)
        self.proj = nn.Linear(dim, dim)
        self.proj_drop = nn.Dropout(proj_drop)
    
    def forward(self, x):
        B, N, C = x.shape
        qkv = self.qkv(x).reshape(B, N, 3, self.num_heads, C // self.num_heads).permute(2, 0, 3, 1, 4)
        q, k, v = qkv[0], qkv[1], qkv[2]
        
        attn = (q @ k.transpose(-2, -1)) * self.scale
        attn = attn.softmax(dim=-1)
        attn = self.attn_drop(attn)
        
        x = (attn @ v).transpose(1, 2).reshape(B, N, C)
        x = self.proj(x)
        x = self.proj_drop(x)
        return x

class SwinTransformerBlock(nn.Module):
    """Swin Transformer Block"""
    def __init__(self, dim, num_heads, window_size=2, mlp_ratio=4., qkv_bias=True,
                 drop=0., attn_drop=0., drop_path=0., act_layer=nn.GELU, norm_layer=nn.LayerNorm):
        super().__init__()
        self.norm1 = norm_layer(dim)
        self.attn = WindowAttention(dim, window_size, num_heads, qkv_bias, attn_drop, drop)
        self.drop_path = nn.Identity()  # 简化，不使用drop_path
        self.norm2 = norm_layer(dim)
        mlp_hidden_dim = int(dim * mlp_ratio)
        self.mlp = nn.Sequential(
            nn.Linear(dim, mlp_hidden_dim),
            act_layer(),
            nn.Dropout(drop),
            nn.Linear(mlp_hidden_dim, dim),
            nn.Dropout(drop)
        )
    
    def forward(self, x):
        x = x + self.drop_path(self.attn(self.norm1(x)))
        x = x + self.drop_path(self.mlp(self.norm2(x)))
        return x

class SwinStage(nn.Module):
    """Swin Transformer Stage"""
    def __init__(self, dim, depth, num_heads, window_size=2, mlp_ratio=4., drop=0., attn_drop=0.):
        super().__init__()
        self.blocks = nn.ModuleList([
            SwinTransformerBlock(dim, num_heads, window_size, mlp_ratio, 
                                drop=drop, attn_drop=attn_drop)
            for _ in range(depth)
        ])
    
    def forward(self, x):
        for block in self.blocks:
            x = block(x)
        return x

class SimplifiedSwinTransformer(nn.Module):
    """简化的 Swin Transformer，适配 6x6 输入"""
    def __init__(self, img_size=6, patch_size=2, in_chans=3, embed_dim=96,
                 depths=[2, 2, 6, 2], num_heads=[3, 6, 12, 24], window_size=2,
                 mlp_ratio=4., drop=0., attn_drop=0.):
        super().__init__()
        self.num_layers = len(depths)
        self.embed_dim = embed_dim
        
        # Patch embedding
        self.patch_embed = PatchEmbedding(img_size, patch_size, in_chans, embed_dim)
        num_patches = self.patch_embed.n_patches
        
        # Stages with dimension expansion
        self.stages = nn.ModuleList()
        dim = embed_dim
        for i, (depth, num_head) in enumerate(zip(depths, num_heads)):
            # 创建stage
            stage = SwinStage(dim, depth, num_head, window_size, mlp_ratio, drop, attn_drop)
            self.stages.append(stage)
            
            # 下一层的维度（简化版，不进行下采样，只扩展维度）
            if i < len(depths) - 1:
                dim_next = dim * 2  # 维度翻倍
                # 添加维度扩展层
                expand_layer = nn.Linear(dim, dim_next)
                self.stages.append(expand_layer)
                dim = dim_next
        
        self.norm = nn.LayerNorm(dim)
        self.feature_dim = dim
    
    def forward(self, x):
        # x: [B, C, H, W]
        x, (H, W) = self.patch_embed(x)  # [B, N, embed_dim]
        
        for module in self.stages:
            if isinstance(module, nn.Linear):
                # 维度扩展
                x = module(x)
            else:
                # SwinStage
                x = module(x)
        
        x = self.norm(x)  # [B, N, dim]
        return x

class SwinTransformerRegression(nn.Module):
    """
    基于 Swin Transformer 的回归模型
    架构：
    1. Input Preprocessing (Depthwise + Pointwise Conv)
    2. Simplified Swin Transformer (特征提取，适配6x6输入)
    3. CBAMC Attention (通道+空间注意力)
    4. Regression Head (Flatten + FC)
    """
    def __init__(self, 
                 in_channels=2,
                 img_size=6,
                 embed_dim=96,
                 depths=[2, 2, 6, 2],
                 num_heads=[3, 6, 12, 24],
                 window_size=2,  # 适配6x6输入
                 pretrained=True):
        super().__init__()
        
        # 输入预处理层
        self.input_preprocessing = InputPreprocessing(
            in_channels=in_channels,
            mid_channels=48,
            out_channels=3
        )
        
        # 简化的 Swin Transformer（适配6x6输入）
        self.swin = SimplifiedSwinTransformer(
            img_size=img_size,
            patch_size=2,  # 6x6 -> 3x3 patches
            in_chans=3,
            embed_dim=embed_dim,
            depths=depths,
            num_heads=num_heads,
            window_size=window_size,
        )
        
        # 获取特征维度
        feature_dim = self.swin.feature_dim
        # 对于6x6输入，patch_size=2，得到3x3=9个patches
        num_patches = (img_size // 2) ** 2  # 9
        
        # CBAMC注意力模块
        # 将 [B, N, C] 转换为 [B, C, H, W] 格式后应用注意力
        self.cbamc = CBAMC(channels=feature_dim, reduction=16)
        
        # 回归头
        # 使用全局平均池化 + 全连接层
        self.regression_head = nn.Sequential(
            nn.AdaptiveAvgPool2d(1),  # [B, C, 1, 1]
            nn.Flatten(),  # [B, C]
            nn.Linear(feature_dim, feature_dim // 2),
            nn.GELU(),
            nn.Dropout(0.3),
            nn.Linear(feature_dim // 2, feature_dim // 4),
            nn.GELU(),
            nn.Dropout(0.2),
            nn.Linear(feature_dim // 4, 1)  # 输出单个回归值
        )
        
        self.num_patches = num_patches
        self.feature_dim = feature_dim
        self._initialize_weights()
    
    def _initialize_weights(self):
        """初始化权重"""
        for m in self.modules():
            if isinstance(m, nn.Conv2d):
                nn.init.kaiming_normal_(m.weight, mode='fan_out', nonlinearity='relu')
            elif isinstance(m, nn.Linear):
                nn.init.kaiming_normal_(m.weight, mode='fan_out', nonlinearity='relu')
                if m.bias is not None:
                    nn.init.constant_(m.bias, 0)
            elif isinstance(m, nn.BatchNorm2d):
                nn.init.constant_(m.weight, 1)
                nn.init.constant_(m.bias, 0)
    
    def forward(self, x):
        # x: [B, 2, 6, 6]
        
        # 1. 输入预处理
        x = self.input_preprocessing(x)  # [B, 3, 6, 6]
        
        # 2. Swin Transformer特征提取
        features = self.swin(x)  # [B, N, C] = [B, 9, feature_dim]
        
        # 转换为 [B, C, H, W] 格式以便应用CBAMC
        B, N, C = features.shape
        # 对于6x6输入，patch_size=2，得到3x3=9个patches
        H = W = int(np.sqrt(N))  # 3
        if H * W == N:
            features = features.transpose(1, 2).reshape(B, C, H, W)  # [B, C, 3, 3]
        else:
            # 如果不是完全平方，使用全局池化
            features = features.mean(dim=1, keepdim=True)  # [B, 1, C]
            features = features.transpose(1, 2).unsqueeze(-1)  # [B, C, 1, 1]
        
        # 3. CBAMC注意力
        features = self.cbamc(features)  # [B, C, H, W]
        
        # 4. 回归头
        output = self.regression_head(features)  # [B, 1]
        
        # 为了保持与原有代码兼容，将输出reshape为 [B, 1, 6, 6]
        # 这里使用插值将输出扩展到原始空间大小
        B = output.shape[0]
        output = output.view(B, 1, 1, 1)
        output = F.interpolate(output, size=(6, 6), mode='bilinear', align_corners=True)
        
        return output  # [B, 1, 6, 6]

class UNetPlusPlusRegression(nn.Module):
    """
    UNet++ for regression tasks, adapted from baseline_clf.py
    Input: (B, 2, 6, 6) - VV, VH bands
    Output: (B, 1, 6, 6) - CHM prediction
    """
    def __init__(self, in_channels=2, out_channels=1, base_channels=32, dropout=0.3):
        super().__init__()

        # configure the number of channels
        nb_filter = [base_channels, base_channels*2, base_channels*4]
        self.pool = nn.MaxPool2d(2, 2)

        self.conv0_0 = ConvBlock(in_channels, nb_filter[0], dropout)
        self.conv1_0 = ConvBlock(nb_filter[0], nb_filter[1], dropout)
        self.conv0_1 = ConvBlock(nb_filter[0] + nb_filter[1], nb_filter[0], dropout)
        self.conv2_0 = ConvBlock(nb_filter[1], nb_filter[2], dropout)
        self.conv1_1 = ConvBlock(nb_filter[1] + nb_filter[2], nb_filter[1], dropout)
        self.conv0_2 = ConvBlock(nb_filter[0]*2 + nb_filter[1], nb_filter[0], dropout)

        # Regression head: output same spatial size as input
        self.regression_head = nn.Sequential(
            nn.Conv2d(nb_filter[0], nb_filter[0] // 2, 3, padding=1, bias=False),
            nn.BatchNorm2d(nb_filter[0] // 2, momentum=0.01),
            nn.GELU(),
            nn.Dropout2d(dropout * 0.5),
            nn.Conv2d(nb_filter[0] // 2, out_channels, 1)
        )

        self._initialize_weights()

    def _initialize_weights(self):
        for m in self.modules():
            if isinstance(m, nn.Conv2d):
                nn.init.kaiming_normal_(m.weight, mode='fan_out', nonlinearity='relu')
            elif isinstance(m, nn.Linear):
                nn.init.kaiming_normal_(m.weight, mode='fan_out', nonlinearity='relu')
                if m.bias is not None:
                    nn.init.constant_(m.bias, 0)
            elif isinstance(m, nn.BatchNorm2d):
                nn.init.constant_(m.weight, 1)
                nn.init.constant_(m.bias, 0)

    def forward(self, x):
        # encoder
        x0_0 = self.conv0_0(x)  # (B, 32, 6, 6)
        x1_0 = self.conv1_0(self.pool(x0_0))  # (B, 64, 3, 3)

        # nested nodes
        x0_1 = self.conv0_1(torch.cat([x0_0, F.interpolate(x1_0, size=x0_0.shape[2:], mode='bilinear', align_corners=True)], 1))  # (B, 32, 6, 6)

        # bottleneck
        x2_0 = self.conv2_0(self.pool(x1_0))  # (B, 128, 1, 1)

        # decoder
        x1_1 = self.conv1_1(torch.cat([x1_0, F.interpolate(x2_0, size=x1_0.shape[2:], mode='bilinear', align_corners=True)], 1))  # (B, 64, 3, 3)
        x0_2 = self.conv0_2(torch.cat([x0_0, x0_1, F.interpolate(x1_1, size=x0_0.shape[2:], mode='bilinear', align_corners=True)], 1))  # (B, 32, 6, 6)

        # Regression output
        output = self.regression_head(x0_2)  # (B, 1, 6, 6)

        return output

"""### Loss and Data Augmentation"""

def create_mask(pred, target):
    """Create mask for valid pixels (not NaN)"""
    return ~torch.isnan(target) & ~torch.isnan(pred)

def mixup_data(x, y, alpha=1.0):
    """
    MixUp数据增强
    Args:
        x: 输入数据 [B, C, H, W]
        y: 目标数据 [B, 1, H, W]
        alpha: MixUp参数（α=1.0）
    Returns:
        mixed_x: 混合后的输入
        y_a, y_b: 两个目标
        lam: 混合系数
    """
    if alpha > 0:
        lam = np.random.beta(alpha, alpha)
    else:
        lam = 1
    
    batch_size = x.size(0)
    index = torch.randperm(batch_size).to(x.device)
    
    mixed_x = lam * x + (1 - lam) * x[index, :]
    y_a, y_b = y, y[index]
    
    return mixed_x, y_a, y_b, lam

def mixup_criterion(criterion, pred, y_a, y_b, lam):
    """
    MixUp损失计算
    Args:
        criterion: 损失函数
        pred: 预测值
        y_a, y_b: 两个目标
        lam: 混合系数
    Returns:
        loss: 混合损失
    """
    return lam * criterion(pred, y_a) + (1 - lam) * criterion(pred, y_b)

class MaskedMSELoss(nn.Module):
    """MSE损失（仅计算有效像素）"""
    def __init__(self):
        super(MaskedMSELoss, self).__init__()

    def forward(self, pred, target):
        """MSE loss computed only on valid pixels"""
        mask = create_mask(pred, target)
        if mask.sum() == 0:
            return torch.tensor(0.0, device=pred.device, requires_grad=True)
        mse = ((pred[mask] - target[mask]) ** 2).mean()
        return mse

class MaskedHuberLoss(nn.Module):
    """Huber损失（仅计算有效像素）"""
    def __init__(self, delta=1.0):
        super(MaskedHuberLoss, self).__init__()
        self.delta = delta

    def forward(self, pred, target):
        """Huber loss computed only on valid pixels"""
        mask = create_mask(pred, target)
        if mask.sum() == 0:
            return torch.tensor(0.0, device=pred.device, requires_grad=True)
        
        error = pred[mask] - target[mask]
        abs_error = torch.abs(error)
        quadratic = torch.clamp(abs_error, max=self.delta)
        linear = abs_error - quadratic
        loss = 0.5 * quadratic ** 2 + self.delta * linear
        return loss.mean()

class MaskedRMSELoss(nn.Module):
    def __init__(self):
        super(MaskedRMSELoss, self).__init__()

    def forward(self, pred, target):
        """RMSE loss computed only on valid pixels"""
        mask = create_mask(pred, target)
        if mask.sum() == 0:
            return torch.tensor(0.0, device=pred.device, requires_grad=True)
        mse = ((pred[mask] - target[mask]) ** 2).mean()
        rmse = torch.sqrt(mse + 1e-8)
        return rmse

def compute_r2(pred, target):
    """Compute R² score"""
    mask = create_mask(pred, target)
    if mask.sum() == 0:
        return 0.0
    pred_valid = pred[mask]
    target_valid = target[mask]
    ss_res = ((target_valid - pred_valid) ** 2).sum()
    ss_tot = ((target_valid - target_valid.mean()) ** 2).sum()
    r2 = (1 - (ss_res / ss_tot)).item() if ss_tot > 0 else 0.0
    return r2

class FocalFrequencyLoss(nn.Module):
    """
    频域损失 - 强调高频细节（对抗过度平滑）
    论文: Jiang et al. "Focal Frequency Loss" (ICCV 2021)
    """
    def __init__(self, alpha=1.0):
        super().__init__()
        self.alpha = alpha

    def forward(self, pred, target):
        # 创建mask，只处理有效像素
        mask = create_mask(pred, target)
        if mask.sum() == 0:
            return torch.tensor(0.0, device=pred.device, requires_grad=True)

        # 对每个样本分别处理（因为mask可能不同）
        batch_size = pred.shape[0]
        losses = []

        for i in range(batch_size):
            pred_i = pred[i:i+1]  # (1, 1, H, W)
            target_i = target[i:i+1]  # (1, 1, H, W)
            mask_i = mask[i:i+1]  # (1, 1, H, W)

            # 只处理有效区域
            if mask_i.sum() == 0:
                continue

            # 将无效值设为0（FFT需要连续数据）
            pred_masked = pred_i.clone()
            target_masked = target_i.clone()
            pred_masked[~mask_i] = 0.0
            target_masked[~mask_i] = 0.0

            # 转到频域
            pred_fft = torch.fft.rfft2(pred_masked)
            target_fft = torch.fft.rfft2(target_masked)

            # 计算频谱差异（使用实部和虚部）
            diff_real = pred_fft.real - target_fft.real
            diff_imag = pred_fft.imag - target_fft.imag
            diff = torch.sqrt(diff_real ** 2 + diff_imag ** 2 + 1e-8)

            # 归一化diff（避免尺度问题）
            diff_normalized = diff / (diff.mean() + 1e-8)

            # Focal 权重：高频分量获得更高权重
            freq_weight = torch.pow(diff_normalized + 1e-8, self.alpha)

            # 加权频域损失（归一化）
            loss = (freq_weight * diff_normalized).mean()
            losses.append(loss)

        if len(losses) == 0:
            return torch.tensor(0.0, device=pred.device, requires_grad=True)

        return torch.stack(losses).mean()

class CombinedLoss(nn.Module):
    """组合空间损失和频域损失"""
    def __init__(self, freq_weight=0.1, alpha=1.0):
        super().__init__()
        self.masked_rmse = MaskedRMSELoss() 
        self.focal_freq = FocalFrequencyLoss(alpha=alpha)
        self.freq_weight = freq_weight

    def forward(self, pred, target):
        spatial_loss = self.masked_rmse(pred, target)
        freq_loss = self.focal_freq(pred, target)
        return spatial_loss + self.freq_weight * freq_loss

