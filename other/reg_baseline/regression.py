def visualize_test_samples(model, test_loader, device, num_samples=4, start_index=0):
    """Visualize test samples with predictions"""
    model.eval()
    samples = []

    with torch.no_grad():
        for i, (inputs, targets) in enumerate(test_loader):
            batch_start = i * test_loader.batch_size
            batch_end = batch_start + inputs.shape[0]

            if batch_end <= start_index or batch_start >= start_index + num_samples:
                continue

            inputs, targets = inputs.to(device), targets.to(device)
            preds = model(inputs)

            for j in range(inputs.shape[0]):
                idx = batch_start + j
                if start_index <= idx < start_index + num_samples:
                    samples.append({
                        'idx': idx,
                        'input': inputs[j].cpu().numpy(),  # (2, H, W) - VV, VH
                        'target': targets[j, 0].cpu().numpy(),
                        'pred': preds[j, 0].cpu().numpy()
                    })

            if len(samples) >= num_samples:
                break

    viridis_nan = cm.get_cmap('viridis').copy()
    viridis_nan.set_bad(color='red')

    # Create figure with 5 columns: VV, VH, Target, Prediction, Colorbar
    fig, axes = plt.subplots(num_samples, 5, figsize=(12, 2.5*num_samples))
    if num_samples == 1:
        axes = axes.reshape(1, -1)

    # Find global min/max for consistent colorbar scale
    all_targets = [s['target'] for s in samples]
    all_preds = [s['pred'] for s in samples]
    valid_targets = np.concatenate([t[~np.isnan(t)] for t in all_targets])
    valid_preds = np.concatenate([p[~np.isnan(p)] for p in all_preds])
    vmin = min(valid_targets.min(), valid_preds.min()) if len(valid_targets) > 0 and len(valid_preds) > 0 else 0
    vmax = max(valid_targets.max(), valid_preds.max()) if len(valid_targets) > 0 and len(valid_preds) > 0 else 40

    for i, s in enumerate(samples):
        # Input bands: VV, VH
        for j, name in enumerate(['VV', 'VH']):
            im = axes[i, j].imshow(s['input'][j], cmap='gray', aspect='auto')
            axes[i, j].set_title(f"Sample {s['idx']}: {name}", fontsize=8)
            axes[i, j].axis('off')

        # Target
        valid_mask = ~np.isnan(s['target'])
        valid_pct = valid_mask.sum() / valid_mask.size * 100
        im_target = axes[i, 2].imshow(s['target'], cmap=viridis_nan, aspect='auto', vmin=vmin, vmax=vmax)
        axes[i, 2].set_title(f"Sample {s['idx']}: True CHM", fontsize=8)
        axes[i, 2].text(0.5, -0.1, f"Valid: {valid_pct:.1f}%",
                       transform=axes[i, 2].transAxes, ha='center', fontsize=6)
        axes[i, 2].axis('off')

        # Prediction
        pred_masked = s['pred'].copy()
        pred_masked[~valid_mask] = np.nan
        im_pred = axes[i, 3].imshow(pred_masked, cmap=viridis_nan, aspect='auto', vmin=vmin, vmax=vmax)
        axes[i, 3].set_title(f"Sample {s['idx']}: Predicted CHM", fontsize=8)

        if valid_mask.any():
            rmse = np.sqrt(np.mean((s['target'][valid_mask] - s['pred'][valid_mask]) ** 2))
            axes[i, 3].text(0.5, -0.1, f"RMSE: {rmse:.2f}m",
                           transform=axes[i, 3].transAxes, ha='center', fontsize=6, color='red')
        axes[i, 3].axis('off')

        # Colorbar (only for first row)
        if i == 0:
            axes[i, 4].axis('off')
            cbar = plt.colorbar(im_pred, ax=axes[i, 4], fraction=1.0, pad=0.1)
            cbar.set_label('CHM (m)', fontsize=8)
            cbar.ax.tick_params(labelsize=6)
        else:
            axes[i, 4].axis('off')

    plt.tight_layout()
    plt.suptitle(f'Test Predictions (Index {start_index}-{start_index+num_samples-1})',
                 fontsize=10, y=1.002)
    plt.savefig('test_samples_visualization.png', dpi=300, bbox_inches='tight')
    plt.show()

    return samples

