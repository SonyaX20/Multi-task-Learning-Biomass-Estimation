class UNetClassifier(nn.Module):
    def __init__(
        self,
        in_channels: int,
        num_classes: int,
        base_channels: int = 32,
        dropout: float = 0.3,
    ) -> None:
        super().__init__()

        self.num_classes = num_classes

        self.enc1 = DoubleConv(in_channels, base_channels)

        self.down1 = Down(
            in_channels=base_channels,
            out_channels=base_channels * 2,
            kernel_size=3,
            stride=2,
            padding=1,
        )
        self.enc2 = DoubleConv(base_channels * 2, base_channels * 2)

        self.down2 = Down(
            in_channels=base_channels * 2,
            out_channels=base_channels * 4,
            kernel_size=3,
            stride=3,
            padding=0,
        )

        self.bottleneck = DoubleConv(base_channels * 4, base_channels * 4)

        self.up2 = Up(
            in_channels=base_channels * 4,
            out_channels=base_channels * 2,
            kernel_size=3,
            stride=3,
        )
        self.dropout2 = nn.Dropout2d(p=dropout)

        self.up1 = Up(
            in_channels=base_channels * 2,
            out_channels=base_channels,
            kernel_size=2,
            stride=2,
        )

        self.out_conv = nn.Conv2d(base_channels, num_classes, kernel_size=1)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        x1 = self.enc1(x)
        x2 = self.down1(x1)

        x3 = self.enc2(x2)
        x4 = self.down2(x3)

        x5 = self.bottleneck(x4)

        x6 = self.up2(x5, x3)
        x6 = self.dropout2(x6)

        x7 = self.up1(x6, x1)

        logits_map = self.out_conv(x7)
        logits = logits_map.mean(dim=(2, 3))
        return logits

