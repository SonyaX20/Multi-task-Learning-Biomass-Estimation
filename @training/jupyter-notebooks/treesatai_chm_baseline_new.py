class MultiTaskUNet(nn.Module):
    """Multi-task U-Net with shared encoder and separate decoders for
    classification (tree species) and regression (CHM).

    The encoder follows the same structure as UNetClassifier/UNetRegressor.
    The classifier head outputs logits of shape (N, num_classes), obtained by
    global average pooling over a logits feature map. The regression head
    outputs a CHM map of shape (N, 1, H, W) with non-negative values.
    """

    def __init__(
        self,
        in_channels: int,
        num_classes: int,
        base_channels: int = 32,
        dropout: float = 0.3,
    ) -> None:
        super().__init__()

        self.num_classes = num_classes

        # Shared encoder
        self.enc1 = DoubleConv(in_channels, base_channels)
        self.down1 = Down(
            in_channels=base_channels,
            out_channels=base_channels * 2,
            kernel_size=3,
            stride=2,
            padding=1,
        )
        self.enc2 = DoubleConv(base_channels * 2, base_channels * 2)
        self.down2 = Down(
            in_channels=base_channels * 2,
            out_channels=base_channels * 4,
            kernel_size=3,
            stride=3,
            padding=0,
        )
        self.bottleneck = DoubleConv(base_channels * 4, base_channels * 4)

        # Classification decoder
        self.up2_cls = Up(
            in_channels=base_channels * 4,
            out_channels=base_channels * 2,
            kernel_size=3,
            stride=3,
        )
        self.dropout2_cls = nn.Dropout2d(p=dropout)
        self.up1_cls = Up(
            in_channels=base_channels * 2,
            out_channels=base_channels,
            kernel_size=2,
            stride=2,
        )
        self.out_conv_cls = nn.Conv2d(base_channels, num_classes, kernel_size=1)

        # Regression decoder
        self.up2_reg = Up(
            in_channels=base_channels * 4,
            out_channels=base_channels * 2,
            kernel_size=3,
            stride=3,
        )
        self.dropout2_reg = nn.Dropout2d(p=dropout)
        self.up1_reg = Up(
            in_channels=base_channels * 2,
            out_channels=base_channels,
            kernel_size=2,
            stride=2,
        )
        self.out_conv_reg = nn.Conv2d(base_channels, 1, kernel_size=1)

    def forward(self, x: torch.Tensor) -> tuple[torch.Tensor, torch.Tensor]:
        # Shared encoder forward
        x1 = self.enc1(x)
        x2 = self.down1(x1)
        x3 = self.enc2(x2)
        x4 = self.down2(x3)
        x5 = self.bottleneck(x4)

        # Classification branch
        xc = self.up2_cls(x5, x3)
        xc = self.dropout2_cls(xc)
        xc = self.up1_cls(xc, x1)
        logits_map = self.out_conv_cls(xc)
        logits = logits_map.mean(dim=(2, 3))  # (N, num_classes)

        # Regression branch
        xr = self.up2_reg(x5, x3)
        xr = self.dropout2_reg(xr)
        xr = self.up1_reg(xr, x1)
        raw_chm = self.out_conv_reg(xr)
        chm = F.softplus(raw_chm)
        chm = torch.clamp(chm, 0.0, CHM_MAX_THRESHOLD)

        return logits, chm


class CrossTaskAttention(nn.Module):
    def __init__(self, channels: int, num_heads: int = 4) -> None:
        super().__init__()
        self.channels = channels
        self.num_heads = num_heads

        self.attn_cls = nn.MultiheadAttention(
            embed_dim=channels,
            num_heads=num_heads,
            batch_first=True,
        )
        self.attn_reg = nn.MultiheadAttention(
            embed_dim=channels,
            num_heads=num_heads,
            batch_first=True,
        )

        self.norm_cls = nn.LayerNorm(channels)
        self.norm_reg = nn.LayerNorm(channels)

    def forward(
        self,
        feat_cls: torch.Tensor,
        feat_reg: torch.Tensor,
    ) -> tuple[torch.Tensor, torch.Tensor]:
        # feat_* shape: (N, C, H, W)
        n, c, h, w = feat_cls.shape
        if feat_reg.shape != feat_cls.shape:
            raise ValueError(
                f"Expected feat_reg with shape {feat_cls.shape}, got {feat_reg.shape}"
            )

        cls_tokens = feat_cls.view(n, c, h * w).transpose(1, 2)  # (N, L, C)
        reg_tokens = feat_reg.view(n, c, h * w).transpose(1, 2)  # (N, L, C)

        cls_q = self.norm_cls(cls_tokens)
        reg_q = self.norm_reg(reg_tokens)

        cls_attended, _ = self.attn_cls(
            query=cls_q,
            key=reg_q,
            value=reg_q,
            need_weights=False,
        )
        reg_attended, _ = self.attn_reg(
            query=reg_q,
            key=cls_q,
            value=cls_q,
            need_weights=False,
        )

        cls_tokens = cls_tokens + cls_attended
        reg_tokens = reg_tokens + reg_attended

        feat_cls_out = cls_tokens.transpose(1, 2).view(n, c, h, w)
        feat_reg_out = reg_tokens.transpose(1, 2).view(n, c, h, w)
        return feat_cls_out, feat_reg_out


class MultiTaskUNetCrossAttention(nn.Module):
    def __init__(
        self,
        in_channels: int,
        num_classes: int,
        base_channels: int = 32,
        dropout: float = 0.3,
        attn_heads: int = 4,
    ) -> None:
        super().__init__()

        self.num_classes = num_classes

        # Shared encoder (same as MultiTaskUNet)
        self.enc1 = DoubleConv(in_channels, base_channels)
        self.down1 = Down(
            in_channels=base_channels,
            out_channels=base_channels * 2,
            kernel_size=3,
            stride=2,
            padding=1,
        )
        self.enc2 = DoubleConv(base_channels * 2, base_channels * 2)
        self.down2 = Down(
            in_channels=base_channels * 2,
            out_channels=base_channels * 4,
            kernel_size=3,
            stride=3,
            padding=0,
        )

        # Task-specific bottlenecks
        self.bottleneck_cls = DoubleConv(base_channels * 4, base_channels * 4)
        self.bottleneck_reg = DoubleConv(base_channels * 4, base_channels * 4)

        # Cross-attention between task-specific bottleneck features
        self.cross_attn = CrossTaskAttention(
            channels=base_channels * 4,
            num_heads=attn_heads,
        )

        # Classification decoder
        self.up2_cls = Up(
            in_channels=base_channels * 4,
            out_channels=base_channels * 2,
            kernel_size=3,
            stride=3,
        )
        self.dropout2_cls = nn.Dropout2d(p=dropout)
        self.up1_cls = Up(
            in_channels=base_channels * 2,
            out_channels=base_channels,
            kernel_size=2,
            stride=2,
        )
        self.out_conv_cls = nn.Conv2d(base_channels, num_classes, kernel_size=1)

        # Regression decoder
        self.up2_reg = Up(
            in_channels=base_channels * 4,
            out_channels=base_channels * 2,
            kernel_size=3,
            stride=3,
        )
        self.dropout2_reg = nn.Dropout2d(p=dropout)
        self.up1_reg = Up(
            in_channels=base_channels * 2,
            out_channels=base_channels,
            kernel_size=2,
            stride=2,
        )
        self.out_conv_reg = nn.Conv2d(base_channels, 1, kernel_size=1)

    def forward(self, x: torch.Tensor) -> tuple[torch.Tensor, torch.Tensor]:
        # Shared encoder forward
        x1 = self.enc1(x)
        x2 = self.down1(x1)
        x3 = self.enc2(x2)
        x4 = self.down2(x3)

        # Task-specific bottleneck features
        b_cls = self.bottleneck_cls(x4)
        b_reg = self.bottleneck_reg(x4)

        # Cross-attention between tasks at bottleneck
        b_cls, b_reg = self.cross_attn(b_cls, b_reg)

        # Classification branch
        xc = self.up2_cls(b_cls, x3)
        xc = self.dropout2_cls(xc)
        xc = self.up1_cls(xc, x1)
        logits_map = self.out_conv_cls(xc)
        logits = logits_map.mean(dim=(2, 3))

        # Regression branch
        xr = self.up2_reg(b_reg, x3)
        xr = self.dropout2_reg(xr)
        xr = self.up1_reg(xr, x1)
        raw_chm = self.out_conv_reg(xr)
        chm = F.softplus(raw_chm)
        chm = torch.clamp(chm, 0.0, CHM_MAX_THRESHOLD)

        return logits, chm


class SharedPrivateConvBlock(nn.Module):
    def __init__(self, in_channels: int, out_channels: int) -> None:
        super().__init__()
        self.shared = DoubleConv(in_channels, out_channels)
        self.cls = DoubleConv(in_channels, out_channels)
        self.reg = DoubleConv(in_channels, out_channels)

        self.alpha = nn.Parameter(torch.ones(out_channels))
        self.beta = nn.Parameter(torch.zeros(out_channels))
        self.gamma = nn.Parameter(torch.ones(out_channels))
        self.delta = nn.Parameter(torch.zeros(out_channels))

        self._last_h_shared: torch.Tensor | None = None
        self._last_h_cls_raw: torch.Tensor | None = None
        self._last_h_reg_raw: torch.Tensor | None = None

    def forward(self, x: torch.Tensor) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
        h_shared = self.shared(x)
        h_cls_raw = self.cls(x)
        h_reg_raw = self.reg(x)

        self._last_h_shared = h_shared
        self._last_h_cls_raw = h_cls_raw
        self._last_h_reg_raw = h_reg_raw

        alpha = self.alpha.view(1, -1, 1, 1)
        beta = self.beta.view(1, -1, 1, 1)
        gamma = self.gamma.view(1, -1, 1, 1)
        delta = self.delta.view(1, -1, 1, 1)

        h_cls = alpha * h_shared + beta * h_cls_raw
        h_reg = gamma * h_shared + delta * h_reg_raw
        return h_shared, h_cls, h_reg

    def orthogonal_loss(self) -> torch.Tensor:
        if self._last_h_shared is None:
            device = self.shared.block[0].weight.device
            return torch.tensor(0.0, device=device)

        h_shared = self._last_h_shared
        h_cls_raw = self._last_h_cls_raw
        h_reg_raw = self._last_h_reg_raw

        n = h_shared.size(0)
        h_s = h_shared.view(n, -1)
        h_c = h_cls_raw.view(n, -1)
        h_r = h_reg_raw.view(n, -1)

        h_s = h_s - h_s.mean(dim=0, keepdim=True)
        h_c = h_c - h_c.mean(dim=0, keepdim=True)
        h_r = h_r - h_r.mean(dim=0, keepdim=True)

        c_sc = torch.matmul(h_s.T, h_c) / max(n, 1)
        c_sr = torch.matmul(h_s.T, h_r) / max(n, 1)
        c_cr = torch.matmul(h_c.T, h_r) / max(n, 1)

        loss = c_sc.pow(2).mean() + c_sr.pow(2).mean() + c_cr.pow(2).mean()
        return loss


class MultiTaskUNetSharedPrivate(nn.Module):
    def __init__(
        self,
        in_channels: int,
        num_classes: int,
        base_channels: int = 32,
        dropout: float = 0.3,
    ) -> None:
        super().__init__()

        self.num_classes = num_classes

        self.enc1_block = SharedPrivateConvBlock(in_channels, base_channels)
        self.down1 = Down(
            in_channels=base_channels,
            out_channels=base_channels * 2,
            kernel_size=3,
            stride=2,
            padding=1,
        )

        self.enc2_cls = DoubleConv(base_channels * 2, base_channels * 2)
        self.down2_cls = Down(
            in_channels=base_channels * 2,
            out_channels=base_channels * 4,
            kernel_size=3,
            stride=3,
            padding=0,
        )
        self.bottleneck_cls = DoubleConv(base_channels * 4, base_channels * 4)

        self.enc2_reg = DoubleConv(base_channels * 2, base_channels * 2)
        self.down2_reg = Down(
            in_channels=base_channels * 2,
            out_channels=base_channels * 4,
            kernel_size=3,
            stride=3,
            padding=0,
        )
        self.bottleneck_reg = DoubleConv(base_channels * 4, base_channels * 4)

        self.up2_cls = Up(
            in_channels=base_channels * 4,
            out_channels=base_channels * 2,
            kernel_size=3,
            stride=3,
        )
        self.dropout2_cls = nn.Dropout2d(p=dropout)
        self.up1_cls = Up(
            in_channels=base_channels * 2,
            out_channels=base_channels,
            kernel_size=2,
            stride=2,
        )
        self.out_conv_cls = nn.Conv2d(base_channels, num_classes, kernel_size=1)

        self.up2_reg = Up(
            in_channels=base_channels * 4,
            out_channels=base_channels * 2,
            kernel_size=3,
            stride=3,
        )
        self.dropout2_reg = nn.Dropout2d(p=dropout)
        self.up1_reg = Up(
            in_channels=base_channels * 2,
            out_channels=base_channels,
            kernel_size=2,
            stride=2,
        )
        self.out_conv_reg = nn.Conv2d(base_channels, 1, kernel_size=1)

    def forward(self, x: torch.Tensor) -> tuple[torch.Tensor, torch.Tensor]:
        x1_shared, x1_cls, x1_reg = self.enc1_block(x)
        x2_shared = self.down1(x1_shared)

        x3_cls = self.enc2_cls(x2_shared)
        x4_cls = self.down2_cls(x3_cls)
        b_cls = self.bottleneck_cls(x4_cls)

        x3_reg = self.enc2_reg(x2_shared)
        x4_reg = self.down2_reg(x3_reg)
        b_reg = self.bottleneck_reg(x4_reg)

        xc = self.up2_cls(b_cls, x3_cls)
        xc = self.dropout2_cls(xc)
        xc = self.up1_cls(xc, x1_cls)
        logits_map = self.out_conv_cls(xc)
        logits = logits_map.mean(dim=(2, 3))

        xr = self.up2_reg(b_reg, x3_reg)
        xr = self.dropout2_reg(xr)
        xr = self.up1_reg(xr, x1_reg)
        raw_chm = self.out_conv_reg(xr)
        chm = F.softplus(raw_chm)
        chm = torch.clamp(chm, 0.0, CHM_MAX_THRESHOLD)

        return logits, chm

    def orthogonal_loss(self) -> torch.Tensor:
        return self.enc1_block.orthogonal_loss()


