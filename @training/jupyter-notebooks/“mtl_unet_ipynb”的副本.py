def collect_regression_pairs(model, loader, device, target_index: int = 0):
    model.eval()
    ys = []
    ps = []
    with torch.no_grad():
        for images, labels_cls, labels_chm in tqdm(loader, desc="Collect reg pairs"):
            images = images.to(device)
            targets = labels_chm.to(device)
            preds = model(images)
            mask = torch.isfinite(targets)
            if mask.any():
                ys.append(targets[mask].detach().cpu().numpy())
                ps.append(preds[mask].detach().cpu().numpy())
    if not ys:
        return np.empty(0, dtype=np.float32), np.empty(0, dtype=np.float32)
    y_true = np.concatenate(ys, axis=0)
    y_pred = np.concatenate(ps, axis=0)
    return y_true, y_pred


def plot_regression_joint_with_hists(
    y_true,
    y_pred,
    xlabel: str,
    ylabel: str,
    max_value: float | None = None,
    bins: int = 60,
):
    y_true = np.asarray(y_true).ravel()
    y_pred = np.asarray(y_pred).ravel()
    mask = np.isfinite(y_true) & np.isfinite(y_pred)
    if max_value is not None:
        mask &= y_true <= max_value
    y_true = y_true[mask]
    y_pred = y_pred[mask]
    if y_true.size == 0:
        print("No valid data to plot.")
        return

    # Subsample points for KDE to speed up plotting on large datasets
    max_points = 50000
    if y_true.size > max_points:
        idx = np.random.choice(y_true.size, max_points, replace=False)
        y_true = y_true[idx]
        y_pred = y_pred[idx]

    rmse = float(np.sqrt(np.mean((y_pred - y_true) ** 2)))
    t_mean = float(y_true.mean())
    ss_res = float(np.sum((y_pred - y_true) ** 2))
    ss_tot = float(np.sum((y_true - t_mean) ** 2))
    r2 = 1.0 - ss_res / ss_tot if ss_tot > 0 else float("nan")

    fig = plt.figure(figsize=(6, 6))
    gs = fig.add_gridspec(
        2,
        2,
        width_ratios=(4, 0.8),
        height_ratios=(0.8, 4),
        wspace=0.05,
        hspace=0.05,
    )

    ax_histx = fig.add_subplot(gs[0, 0])
    ax_joint = fig.add_subplot(gs[1, 0])
    ax_histy = fig.add_subplot(gs[1, 1], sharey=ax_joint)

    ax_histx.hist(
        y_true,
        bins=bins,
        color="#1f77b4",
        edgecolor="black",
        linewidth=0.5,
    )
    ax_histx.set_ylabel("Count")
    ax_histx.tick_params(labelbottom=False)
    # Use ScalarFormatter to get scientific notation on the y-axis without offset text
    y_formatter = mticker.ScalarFormatter(useMathText=True)
    y_formatter.set_powerlimits((0, 0))
    ax_histx.yaxis.set_major_formatter(y_formatter)

    ax_histy.hist(
        y_pred,
        bins=bins,
        orientation="horizontal",
        color="#1f77b4",
        edgecolor="black",
        linewidth=0.5,
    )
    ax_histy.set_xlabel("Count")
    ax_histy.tick_params(labelleft=False)
    x_formatter = mticker.ScalarFormatter(useMathText=True)
    x_formatter.set_powerlimits((0, 0))
    ax_histy.xaxis.set_major_formatter(x_formatter)

    if max_value is None:
        min_plot = 0.0
        max_plot = max(float(y_true.max()), float(y_pred.max()))
    else:
        min_plot = 0.0
        max_plot = float(max_value)
        ax_histx.set_xlim(min_plot, max_plot)
        ax_histy.set_ylim(min_plot, max_plot)

    # KDE density surface (reduced levels for speed)
    sns.kdeplot(
        x=y_true,
        y=y_pred,
        fill=True,
        cmap="jet",
        levels=20,
        thresh=0.0,
        ax=ax_joint,
    )

    # Outer density contour as outline
    sns.kdeplot(
        x=y_true,
        y=y_pred,
        fill=False,
        colors="k",
        linewidths=0.8,
        levels=[0.001],
        ax=ax_joint,
    )
    ax_joint.plot(
        [min_plot, max_plot],
        [min_plot, max_plot],
        linestyle="--",
        color="k",
        linewidth=1.0,
    )
    ax_joint.set_xlim(min_plot, max_plot)
    ax_joint.set_ylim(min_plot, max_plot)
    ax_joint.set_xlabel(xlabel)
    ax_joint.set_ylabel(ylabel)
    ax_joint.text(
        0.5,
        0.95,
        f"R² = {r2:.3f}, RMSE = {rmse:.3f}",
        transform=ax_joint.transAxes,
        ha="center",
        va="top",
    )

    plt.show()

