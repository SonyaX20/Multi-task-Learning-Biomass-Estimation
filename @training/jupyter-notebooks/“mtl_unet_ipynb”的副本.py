CHM_MIN_THRESHOLD = 2
CHM_MAX_THRESHOLD = 50.0
CHM_PHYSICAL_MAX = CHM_MAX_THRESHOLD
S1_MIN_THRESHOLD = -10.0
S1_MAX_THRESHOLD = 10

class MultiTaskDataset(Dataset):
    def __init__(self, images: np.ndarray, labels: np.ndarray):
        super().__init__()
        if images.ndim != 4:
            raise ValueError(f"Expected images of shape (N, C, H, W), got {images.shape}")
        if images.shape[1] < 4:
            raise ValueError(
                f"Expected at least 4 channels (3 S1 + 1 CHM), got C={images.shape[1]}"
            )

        # Expected channel order from preprocessing: [VV, VH, VV/VH, CHM]
        # S1 inputs: bands 0,1,2 → clamp to [S1_MIN_THRESHOLD, S1_MAX_THRESHOLD]
        inputs = images[:, 0:3, ...].astype(np.float32)
        inputs = np.clip(inputs, S1_MIN_THRESHOLD, S1_MAX_THRESHOLD)
        self.inputs = torch.from_numpy(inputs)

        # CHM: band 3 → mask out-of-range to NaN
        chm = images[:, 3, ...].astype(np.float32)
        mask_invalid = (chm < CHM_MIN_THRESHOLD) | (chm > CHM_MAX_THRESHOLD)
        chm[mask_invalid] = np.nan
        self.chm_targets = torch.from_numpy(chm).unsqueeze(1)

        # Multi-label classification targets
        labels_arr = np.asarray(labels).astype(np.float32)
        if labels_arr.ndim != 2:
            raise ValueError(
                f"Expected labels of shape (N, num_classes) for multi-label, got {labels_arr.shape}"
            )
        self.cls_targets = torch.from_numpy(labels_arr)

    def __len__(self):
        return self.inputs.shape[0]

    def __getitem__(self, idx):
        x = self.inputs[idx]
        y_cls = self.cls_targets[idx]
        y_chm = self.chm_targets[idx]
        return x, y_cls, y_chm

