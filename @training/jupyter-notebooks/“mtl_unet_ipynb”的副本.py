class MLPClassifier(nn.Module):
    def __init__(
        self,
        in_channels: int,
        num_classes: int,
        height: int = 6,
        width: int = 6,
        hidden_dims: tuple[int, ...] = (256, 256),
        dropout: float = 0.3,
    ) -> None:
        super().__init__()
        self.in_channels = in_channels
        self.height = height
        self.width = width
        in_features = in_channels * height * width

        layers = []
        prev_dim = in_features
        for h in hidden_dims:
            layers.append(nn.Linear(prev_dim, h))
            layers.append(nn.BatchNorm1d(h))
            layers.append(nn.ReLU(inplace=True))
            if dropout > 0.0:
                layers.append(nn.Dropout(p=dropout))
            prev_dim = h
        layers.append(nn.Linear(prev_dim, num_classes))
        self.mlp = nn.Sequential(*layers)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        if x.dim() == 4:
            x = x.view(x.size(0), -1)
        return self.mlp(x)


class MLPRegressor(nn.Module):
    def __init__(
        self,
        in_channels: int,
        height: int = 6,
        width: int = 6,
        hidden_dims: tuple[int, ...] = (256, 256),
        dropout: float = 0.3,
    ) -> None:
        super().__init__()
        self.in_channels = in_channels
        self.height = height
        self.width = width
        in_features = in_channels * height * width
        out_features = height * width

        layers = []
        prev_dim = in_features
        for h in hidden_dims:
            layers.append(nn.Linear(prev_dim, h))
            layers.append(nn.BatchNorm1d(h))
            layers.append(nn.ReLU(inplace=True))
            if dropout > 0.0:
                layers.append(nn.Dropout(p=dropout))
            prev_dim = h
        layers.append(nn.Linear(prev_dim, out_features))
        self.mlp = nn.Sequential(*layers)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        if x.dim() == 4:
            x = x.view(x.size(0), -1)
        out = self.mlp(x)
        batch_size = out.size(0)
        out = out.view(batch_size, 1, self.height, self.width)
        out = F.softplus(out)
        out = torch.clamp(out, 0.0, CHM_PHYSICAL_MAX)
        return out


class MultiTaskMLP(nn.Module):
    def __init__(
        self,
        in_channels: int,
        num_classes: int,
        height: int = 6,
        width: int = 6,
        hidden_dims_cls: tuple[int, ...] = (256, 256),
        hidden_dims_reg: tuple[int, ...] = (256, 256),
        dropout: float = 0.3,
        use_uncertainty_loss: bool = True,
        cls_weight: float = 1.0,
        reg_weight: float = 0.5,
    ) -> None:
        super().__init__()
        self.use_uncertainty_loss = use_uncertainty_loss
        self.cls_weight = cls_weight
        self.reg_weight = reg_weight
        self.min_task_weight = 0.1
        self.max_task_weight = 5.0
        self.num_classes = num_classes

        self.cls_mlp = MLPClassifier(
            in_channels=in_channels,
            num_classes=num_classes,
            height=height,
            width=width,
            hidden_dims=hidden_dims_cls,
            dropout=dropout,
        )
        self.reg_mlp = MLPRegressor(
            in_channels=in_channels,
            height=height,
            width=width,
            hidden_dims=hidden_dims_reg,
            dropout=dropout,
        )

        if self.use_uncertainty_loss:
            self.log_sigma_cls = nn.Parameter(torch.zeros(1))
            self.log_sigma_reg = nn.Parameter(torch.zeros(1))

    def forward(self, x: torch.Tensor) -> tuple[torch.Tensor, torch.Tensor]:
        logits = self.cls_mlp(x)
        chm = self.reg_mlp(x)
        return logits, chm

    def compute_total_loss(
        self,
        loss_cls: torch.Tensor,
        loss_reg: torch.Tensor,
    ) -> torch.Tensor:
        if self.use_uncertainty_loss:
            w_cls = 0.5 * torch.exp(-self.log_sigma_cls)
            w_reg = 0.5 * torch.exp(-self.log_sigma_reg)

            w_min = self.min_task_weight
            w_max = self.max_task_weight
            w_cls = torch.clamp(w_cls, w_min, w_max)
            w_reg = torch.clamp(w_reg, w_min, w_max)

            loss = w_cls * loss_cls + w_reg * loss_reg
            return loss
        return self.cls_weight * loss_cls + self.reg_weight * loss_reg

    def get_task_weights(self) -> tuple[float, float]:
        if self.use_uncertainty_loss:
            w_cls = 0.5 * torch.exp(-self.log_sigma_cls)
            w_reg = 0.5 * torch.exp(-self.log_sigma_reg)

            w_min = self.min_task_weight
            w_max = self.max_task_weight
            w_cls = torch.clamp(w_cls, w_min, w_max)
            w_reg = torch.clamp(w_reg, w_min, w_max)
        else:
            first_param = next(self.parameters())
            device = first_param.device
            w_cls = torch.tensor(self.cls_weight, device=device)
            w_reg = torch.tensor(self.reg_weight, device=device)
        return float(w_cls.item()), float(w_reg.item())

class DoubleConv(nn.Module):
    def __init__(self, in_channels: int, out_channels: int) -> None:
        super().__init__()
        self.block = nn.Sequential(
            nn.Conv2d(in_channels, out_channels, kernel_size=3, padding=1, bias=False),
            nn.BatchNorm2d(out_channels),
            nn.ReLU(inplace=True),
            nn.Conv2d(out_channels, out_channels, kernel_size=3, padding=1, bias=False),
            nn.BatchNorm2d(out_channels),
            nn.ReLU(inplace=True),
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.block(x)


class Down(nn.Module):
    def __init__(
        self,
        in_channels: int,
        out_channels: int,
        kernel_size: int,
        stride: int,
        padding: int,
    ) -> None:
        super().__init__()
        self.block = nn.Sequential(
            nn.Conv2d(
                in_channels,
                out_channels,
                kernel_size=kernel_size,
                stride=stride,
                padding=padding,
                bias=False,
            ),
            nn.BatchNorm2d(out_channels),
            nn.ReLU(inplace=True),
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.block(x)


class Up(nn.Module):
    def __init__(
        self,
        in_channels: int,
        out_channels: int,
        kernel_size: int,
        stride: int,
    ) -> None:
        super().__init__()
        self.up = nn.ConvTranspose2d(
            in_channels,
            in_channels // 2,
            kernel_size=kernel_size,
            stride=stride,
        )
        # after upsampling, features are concatenated with skip connection
        # so DoubleConv expects in_channels and produces out_channels
        self.conv = DoubleConv(in_channels, out_channels)

    def forward(self, x: torch.Tensor, skip: torch.Tensor) -> torch.Tensor:
        x = self.up(x)
        x = torch.cat([x, skip], dim=1)
        x = self.conv(x)
        return x


class UNetRegressor(nn.Module):
    def __init__(
        self,
        in_channels: int,
        base_channels: int = 32,
        dropout: float = 0.3,
    ) -> None:
        super().__init__()

        self.enc1 = DoubleConv(in_channels, base_channels)

        self.down1 = Down(
            in_channels=base_channels,
            out_channels=base_channels * 2,
            kernel_size=3,
            stride=2,
            padding=1,
        )
        self.enc2 = DoubleConv(base_channels * 2, base_channels * 2)

        self.down2 = Down(
            in_channels=base_channels * 2,
            out_channels=base_channels * 4,
            kernel_size=3,
            stride=3,
            padding=0,
        )

        self.bottleneck = DoubleConv(base_channels * 4, base_channels * 4)

        self.up2 = Up(
            in_channels=base_channels * 4,
            out_channels=base_channels * 2,
            kernel_size=3,
            stride=3,
        )
        self.dropout2 = nn.Dropout2d(p=dropout)

        self.up1 = Up(
            in_channels=base_channels * 2,
            out_channels=base_channels,
            kernel_size=2,
            stride=2,
        )

        self.out_conv = nn.Conv2d(base_channels, 1, kernel_size=1)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        x1 = self.enc1(x)
        x2 = self.down1(x1)

        x3 = self.enc2(x2)
        x4 = self.down2(x3)

        x5 = self.bottleneck(x4)

        x6 = self.up2(x5, x3)
        x6 = self.dropout2(x6)

        x7 = self.up1(x6, x1)

        raw = self.out_conv(x7)
        chm = F.softplus(raw)
        chm = torch.clamp(chm, 0.0, CHM_PHYSICAL_MAX)
        return chm


class UNetClassifier(nn.Module):
    def __init__(
        self,
        in_channels: int,
        num_classes: int,
        base_channels: int = 32,
        dropout: float = 0.3,
    ) -> None:
        super().__init__()

        self.num_classes = num_classes

        self.enc1 = DoubleConv(in_channels, base_channels)

        self.down1 = Down(
            in_channels=base_channels,
            out_channels=base_channels * 2,
            kernel_size=3,
            stride=2,
            padding=1,
        )
        self.enc2 = DoubleConv(base_channels * 2, base_channels * 2)

        self.down2 = Down(
            in_channels=base_channels * 2,
            out_channels=base_channels * 4,
            kernel_size=3,
            stride=3,
            padding=0,
        )

        self.bottleneck = DoubleConv(base_channels * 4, base_channels * 4)

        self.up2 = Up(
            in_channels=base_channels * 4,
            out_channels=base_channels * 2,
            kernel_size=3,
            stride=3,
        )
        self.dropout2 = nn.Dropout2d(p=dropout)

        self.up1 = Up(
            in_channels=base_channels * 2,
            out_channels=base_channels,
            kernel_size=2,
            stride=2,
        )

        self.out_conv = nn.Conv2d(base_channels, num_classes, kernel_size=1)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        x1 = self.enc1(x)
        x2 = self.down1(x1)

        x3 = self.enc2(x2)
        x4 = self.down2(x3)

        x5 = self.bottleneck(x4)

        x6 = self.up2(x5, x3)
        x6 = self.dropout2(x6)

        x7 = self.up1(x6, x1)

        logits_map = self.out_conv(x7)
        logits = logits_map.mean(dim=(2, 3))
        return logits

